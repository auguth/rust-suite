/// Builds a hidden implementation-side consistency checker for affiliate
/// counter relationships.
///
/// This item exists to validate that implementation-defined affiliate
/// counters form a coherent instance graph.
///
/// Unlike structural affiliates such as *Reverse* and *Ceil*, semantic
/// affiliates such as *Next*, *Back*, and *Floor* are supplied by
/// implementation-side expansion.
///
/// Consequently, the proc-macro cannot assume those relationships are
/// internally consistent.
///
/// ## Canonical Chain Validation
///
/// The generated checker allows implementation-side expansion to verify
/// that semantic affiliate relationships form a single canonical
/// predecessor/successor chain.
///
/// ```text
/// current
///     == back(next(current))
///
/// current
///     == next(back(current))
/// ```
///
/// whenever both neighboring instances exist.
///
/// These invariants ensure that:
///
/// - successor relationships are reversible,
/// - predecessor relationships are reversible,
/// - affiliate transitions remain internally consistent,
/// - and no rogue instance implementations exist outside the canonical
///   instance graph.
///
/// ## Why this exists
///
/// Structural affiliates are derived directly from the current counters
/// and therefore cannot diverge.
///
/// Semantic affiliates are different.
///
/// Since implementations are responsible for supplying:
///
/// - `NextAffiliateCounters`,
/// - `BackAffiliateCounters`,
/// - `FloorAffiliateCounters`,
/// - and their corresponding instance projections,
///
/// invalid affiliate relationships could otherwise create:
///
/// - disconnected instance chains,
/// - multiple predecessors,
/// - multiple successors,
/// - unreachable instances,
/// - or contradictory affiliate topologies.
///
/// The generated checker provides a compile-time assertion point used by
/// implementation-side expansion to validate those relationships.
///
/// ## Generated Item
///
/// ```ignore
/// #[doc(hidden)]
/// const __AffiliateCountersChecker: ();
/// ```
///
/// Implementation-side expansion resolves this unit constant into a
/// collection of compile-time assertions verifying affiliate graph
/// consistency.
///
/// The trait-side declaration merely reserves a location for those
/// assertions.
#[derive(Clone, Debug)]
pub(crate) struct AffiliateCountersChecker;

impl Extension<TraitItemConst, ItemTrait> for AffiliateCountersChecker {
    fn raw_extend(&self, _: &ItemTrait, _: &()) -> Result<TraitItemConst, TokenStream> {
        let ident = gen_const_ident::<Self>();
        let ty = parse_quote!(());
        let item = TraitItemConst {
            attrs: proc_suite::internal_code(),
            ident,
            default: None,
            ty,
            const_token: Default::default(),
            generics: Default::default(),
            colon_token: Default::default(),
            semi_token: Default::default(),
        };
        Ok(item)
    }

    fn validate_extend(
        &self,
        item: Option<&TraitItemConst>,
        towards: &ItemTrait,
        _: Option<&()>,
    ) -> Result<(), TokenStream> {
        let ident = gen_const_ident::<Self>();
        let expected_ty: Type = parse_quote!(());

        validate_trait_const! {
            item: item,
            towards: towards,
            ident: ident,
            ty: expected_ty,
            expr: None => {
                not_found: AffiliateBugs::AffiliateCountersCheckerNotFound {},
                wrong_ident: AffiliateBugs::AffiliateCountersCheckerWrongIdent {},
                wrong_ty: AffiliateBugs::AffiliateCountersCheckerNotUnitType {},
                has_generics: AffiliateBugs::AffiliateCountersCheckerHasGenerics {},
                has_expr: AffiliateBugs::AffiliateCountersCheckerHasExpr {},
            }
        }
    }
}
