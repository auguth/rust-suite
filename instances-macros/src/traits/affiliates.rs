//! This module provides a way for one trait instance to refer to *other*
//! instantiations of the same trait on the same `Self` type.
//!
//! Affiliate relationships are encoded through typenum-backed counter tuples
//! and hidden associated items generated by proc macros.
//!
//! ## Why this exists
//!
//! Rust traits cannot naturally express relationships between multiple
//! instantiations of the same trait.
//!
//! For example, even if both exist:
//!
//! ```ignore
//! K<(U0, U0, U4)>
//! K<(U0, U0, U5)>
//! ```
//!
//! there is no built-in way for one instance to:
//!
//! - navigate to the other,
//! - prove the other exists,
//! - or encode structural relationships between them.
//!
//! This module works around that limitation by generating hidden associated
//! items directly inside the trait.
//!
//! ## What an affiliate is
//!
//! An **affiliate** is another instantiation of the same trait represented
//! through:
//!
//! - hidden associated counter items,
//! - and a hidden associated instance projection.
//!
//! Together, these reconstruct another valid instantiation of the original
//! trait with different counters.
//!
//! ```ignore
//! <Self as MyTrait<(U0, U0, U5)>>::NextAffiliateInstance
//! ```
//!
//! behaves like:
//!
//! ```ignore
//! MyTrait<(U0, U0, U6)>
//! ```
//!
//! while:
//!
//! ```ignore
//! <Self as MyTrait<(U0, U0, U5)>>::ReverseAffiliateInstance
//! ```
//!
//! behaves like:
//!
//! ```ignore
//! MyTrait<(U0, U0, U4)>
//! ```
//!
//! The exact meaning of an affiliate is determined by the affiliate family.
//!
//! ## Affiliate Families
//!
//! This module provides several affiliate families.
//!
//! ### Structural Affiliates
//!
//! Structural affiliates are mechanically derivable from the current counter
//! tuple.
//!
//! These are always locally determinable from the counter tuple.
//!
//! - [`ReverseAffiliate`]
//!     Structural reverse projection.
//!
//! - [`CeilAffiliate`]
//!     Structural canonicalization / jump-table projection.
//!
//! ### Semantic Affiliates
//!
//! Semantic affiliates requires instance graph relations to compute the counter.
//!
//! These describe relationships in the implementation graph rather than purely
//! structural counter transforms.
//!
//! - [`NextAffiliate`]
//!     Canonical semantic successor.
//!
//! - [`BackAffiliate`]
//!     Canonical semantic predecessor.
//!
//! - [`FloorAffiliates`]
//!     Canonical semantic representatives / floor projections (multiple).
//!
//! ### Checkers
//!
//! - [`AffiliateCountersChecker`]
//!     Defines a checkpoint to evaluate rogue
//!     (out of canonical-chain) instance implementations.
//!
//! ## Counter Tuples
//!
//! Affiliates operate over `typenum`-backed counter tuples rather than raw
//! const generics.
//!
//! ```ignore
//! (U0, U1, U5)
//! ```
//!
//! acts like a positional counter space.
//!
//! Affiliates transform or reinterpret those counters to navigate between
//! related trait instances.
//!
//! ## Affiliate Components
//!
//! Every affiliate family generates:
//!
//! - an affiliated counter projection,
//! - and an affiliated instance projection.
//!
//! The counter projection computes or stores the affiliated counter tuple,
//! while the instance projection reconstructs the corresponding trait
//! instantiation for the same `Self` type.
//!
//! ## Hidden Generated Items
//!
//! Each affiliate family injects hidden associated items into the trait:
//!
//! - affiliate counters
//! - affiliate instance projections
//!
//! The generated identifiers are deterministic random names known only
//! to this proc-macro crate.
//!
//! This prevents user code from forging affiliate transitions while allowing
//! implementation-side macros to reconstruct affiliate topology safely.
//!
//! ## Sum-Type Relationships
//!
//! Affiliate instance projections also preserve the associated-type equality
//! relationships established by [`crate::traits::sum`].
//!
//! When an affiliate reconstructs another instantiation of the same trait,
//! `#[sum]` associated types are carried into the reconstructed trait
//! instantiation as explicit associated-type equalities:
//!
//! ```ignore
//! MyTrait<AffiliateCounters, Value = Self::Value>
//! ```
//!
//! Thus, navigation between affiliated instances preserves the type identity
//! of sum-associated types rather than introducing a separate instance-specific
//! type. The affiliate relationship and the sum-type equality relationship are
//! therefore maintained together across recursive instance projections.
//!
//! ## What this enables
//!
//! Affiliates make it possible to:
//!
//! - navigate between related trait instances,
//! - define recursive instance families,
//! - express structural and semantic transitions,
//! - encode compile-time instance graphs,
//! - build jump-table style projections,
//! - and recursively access associated items across related instances.
//!
//! All of this works entirely at compile time without runtime values or
//! unstable language features.

