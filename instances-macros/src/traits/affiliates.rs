define_affiliate! {

    affiliate {
        /// Builds all hidden trait items required for the **Next**
        /// affiliate family.
        ///
        /// For a general explanation of *affiliates*, see the module-level
        /// documentation.
        ///
        /// Next defines the canonical semantic successor relation over a
        /// typenum-backed implementation instance space.
        ///
        /// Unlike structural affiliates such as *Reverse* or *Ceil*, Next
        /// is implementation-defined and therefore cannot be recursively
        /// proven through trait bounds.
        ///
        /// ## Forward-Step Semantics
        ///
        /// Next treats the counter tuple as a positional number.
        ///
        /// Starting from the rightmost counter:
        ///
        /// - locate the first counter strictly less than `MAX`,
        /// - increment it,
        /// - reset all lower-order counters to zero,
        /// - and leave higher-order counters unchanged.
        ///
        /// Examples:
        ///
        /// ```text
        /// [4]         -> [5]
        /// [3, 1]      -> [3, 2]
        /// [3, MAX]    -> [4, 0]
        /// ```
        ///
        /// If all counters are already at `MAX`, the instance space is
        /// exhausted.
        ///
        /// ## Generated Items
        ///
        /// This affiliate injects:
        ///
        /// - [`NextAffiliateCounters`]
        ///     Computes the canonical successor counter tuple.
        ///
        /// - [`NextAffiliateInstance`]
        ///     Projects the current trait into its semantic successor
        ///     instance.
        ///
        /// ## Hidden Resolution
        ///
        /// Generated affiliate identifiers are deterministic random symbols
        /// known only to this proc-macro crate.
        ///
        /// This prevents user code from forging affiliate transitions while
        /// allowing implementation-side macros to reconstruct successor
        /// topology safely.
        NextAffiliate
    },

    counters {
        /// Generates the canonical semantic successor counter tuple.
        ///
        /// ```ignore
        /// type NextAffiliateCounters =
        ///     /* next counter tuple */;
        /// ```
        ///
        /// The tuple is computed using positional forward-stepping
        /// semantics.
        ///
        /// Examples:
        ///
        /// ```text
        /// (0,0,0) -> (0,0,1)
        /// (0,0,9) -> (0,1,0)
        /// (0,4,9) -> (0,5,0)
        /// (8,9,9) -> (9,0,0)
        /// ```
        ///
        /// Unlike structural affiliates, existence of the generated
        /// successor is validated on the implementation side rather than
        /// through recursive trait bounds.
        NextAffiliateCounters
    },

    instance {
        /// Generates the semantic next-instance projection.
        ///
        /// ```ignore
        /// type NextAffiliateInstance:
        ///     MyTrait<Self::NextAffiliateCounters>;
        /// ```
        ///
        /// Unlike structural affiliates, this projection does not recursively
        /// prove that the next instance exists.
        ///
        /// Instead, it represents a semantic successor edge resolved during
        /// implementation-side expansion.
        ///
        /// Additionally, preserves the associated-type equality relationships established by
        /// [`crate::traits::sum`] for `#[sum]` associated types.
        ///
        /// ## Example
        ///
        /// ```ignore
        /// trait Woo<Counters> {
        ///     #[sum]
        ///     type Value;
        ///
        ///     const VALUE: u8;
        ///
        ///     type NextAffiliateCounters;
        ///
        ///     type NextAffiliateInstance:
        ///         Woo<Self::NextAffiliateCounters, Value = Self::Value>;
        /// }
        ///
        /// impl Woo<(U0, U0, U0)> for Test {
        ///     const VALUE: u8 = 0;
        ///
        ///     type NextAffiliateCounters = (U0, U0, U1);
        ///     type NextAffiliateInstance = Self;
        /// }
        ///
        /// impl Woo<(U0, U0, U1)> for Test {
        ///     const VALUE: u8 = 1;
        ///
        ///     type NextAffiliateCounters = (U0, U1, U0);
        ///     type NextAffiliateInstance = Self;
        /// }
        ///
        /// impl Woo<(U0, U1, U0)> for Test {
        ///     const VALUE: u8 = 2;
        ///
        ///     type NextAffiliateCounters = (U0, U1, U1);
        ///     type NextAffiliateInstance = Self;
        /// }
        ///
        /// let current = <Test as Woo<(U0, U0, U1)>>::VALUE;
        ///
        /// let next = <
        ///     <Test as Woo<(U0, U0, U1)>>::NextAffiliateInstance
        ///         as Woo<
        ///             <Test as Woo<(U0, U0, U1)>>::NextAffiliateCounters
        ///         >
        /// >::VALUE;
        ///
        /// assert_eq!(current, 1);
        /// assert_eq!(next, 2);
        /// ```
        ///
        /// The generated projection already carries the required successor
        /// relationship, so callers never need to manually reconstruct the
        /// transition.
        ///
        /// This acts as:
        ///
        /// - a semantic successor edge,
        /// - a proc-macro-resolvable affiliate witness,
        /// - and a type-safe projection into the next instance.
        NextAffiliateInstance
    },

    bugs: AffiliateBugs,
}

