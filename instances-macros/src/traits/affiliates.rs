/// Builds all hidden trait items required for the **Floor**
/// affiliate family.
///
/// For a general explanation of *affiliates*, see the module-level
/// documentation.
///
/// Floor represents the semantic boundary relation of an individual
/// counter dimension.
///
/// Unlike structural affiliates such as *Reverse* or *Ceil*, Floor
/// is implementation-defined and cannot be derived mechanically from
/// the current counters.
///
/// ## Boundary Semantics
///
/// Every counter dimension may have its own semantic boundary.
///
/// Consider:
///
/// ```text
/// [Region, Product]
/// ```
///
/// The boundary reached by traversing the `Region` dimension may be
/// different from the boundary reached by traversing the `Product`
/// dimension.
///
/// Consequently a single instance may participate in multiple floor
/// relationships simultaneously.
///
/// Floor therefore operates per counter dimension rather than over
/// the counter tuple as a whole.
///
/// ## Relationship to Ceil
///
/// Floor acts as the semantic counterpart to the structural *Ceil*
/// affiliate.
///
/// ```text
/// Next  <-> Back
/// Ceil  <-> Floor
/// ```
///
/// where:
///
/// - *Next* and *Back* traverse semantic adjacency,
/// - *Ceil* provides structural canonicalization,
/// - and *Floor* provides semantic boundary navigation.
///
/// ## Generated Items
///
/// For every counter dimension this affiliate injects:
///
/// - a floor-counter projection,
/// - and a floor-instance projection.
///
/// Each pair represents the semantic boundary associated with a
/// particular counter dimension.
///
/// ## Hidden Resolution
///
/// Generated affiliate identifiers are deterministic random symbols
/// known only to this proc-macro crate.
///
/// This prevents user code from forging affiliate transitions while
/// allowing implementation-side macros to reconstruct semantic
/// boundary topology safely.
#[derive(Clone, Debug)]
pub(crate) struct FloorAffiliates;

