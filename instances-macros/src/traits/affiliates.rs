///
/// Therefore:
///
/// ```text
/// FloorAffiliatesCounters_0
/// FloorAffiliatesCounters_1
/// ```
///
/// may resolve to different counter tuples even when evaluated from
/// the same instance.
///
/// This acts as the compile-time representation of the semantic
/// boundary counters associated with a specific counter dimension.
#[derive(Clone, Debug)]
pub(crate) struct FloorAffiliatesCounters;

impl<'a> Extension<Vec<TraitItemType>, ItemTrait, CounterParamsSlice<'a>>
    for FloorAffiliatesCounters
{
    fn raw_extend(
        &self,
        _towards: &ItemTrait,
        context: &CounterParamsSlice<'a>,
    ) -> Result<Vec<TraitItemType>, TokenStream> {
        let mut collect = Vec::new();
        for c in context.iter() {
            let ident = gen_type_ident_with_suffix::<FloorAffiliatesCounters>(Some(
                c.generic_index.to_string().as_bytes(),
            ));

            let crate_of = Instance::support_crate();

            let mut bounds = Punctuated::<TypeParamBound, Plus>::new();

            let mut make_affiliate_bound = |afl| {
                let bound = parse_quote!(
                    #crate_of::DirectAffiliate<
                        #crate_of::#afl
                    >
                );

                bounds.push(TypeParamBound::Trait(bound));
            };

            make_affiliate_bound(format_ident!("Reverse"));

            make_affiliate_bound(format_ident!("Ceil"));

            collect.push(TraitItemType {
                attrs: proc_suite::internal_code(),
                ident,
                default: None,
                type_token: Default::default(),
                generics: Default::default(),
                colon_token: Default::default(),
                bounds,
                semi_token: Default::default(),
            })
        }
        Ok(collect)
    }

    fn validate_extend(
        &self,
        item: Option<&Vec<TraitItemType>>,
        towards: &ItemTrait,
        context: Option<&CounterParamsSlice<'a>>,
    ) -> Result<(), TokenStream> {
        let extracted;
        let counters = match context {
            Some(c) => c,
            None => {
                extracted = CounterParams::checked_extract(towards, &None)?;
                extracted.as_slice().as_ref().as_ref()
            }
        };

        for c in counters.iter() {
            let expected_ident =
                gen_type_ident_with_suffix::<Self>(Some(c.generic_index.to_string().as_bytes()));

            let crate_of = Instance::support_crate();

            let make_affiliate_bound = |afl| -> syn::TraitBound {
                parse_quote!(
                    #crate_of::DirectAffiliate<
                        #crate_of::#afl
                    >
                )
            };

            let rev_bound = make_affiliate_bound(format_ident!("Reverse"));

            let ceil_bound = make_affiliate_bound(format_ident!("Ceil"));

            let bounds = &[rev_bound, ceil_bound];

            validate_trait_types! {
                items: item,
                towards: towards,

                ident: expected_ident,

                bounds: bounds => {
                    not_found:
                        AffiliateBugs::
                            FloorAffiliatesCountersMissing {},
                    wrong_ident:
                        AffiliateBugs::
                            FloorAffiliatesCountersInvalidIdent {},
                    has_generics:
                        AffiliateBugs::
                            FloorAffiliatesCountersHasGenerics {},
                    bound_not_found:
                        AffiliateBugs::
                            FloorAffiliatesCountersBoundNotFound {},
                }
            };
        }
        Ok(())
    }
}

