/// Defines an affiliate family whose relationships are resolved entirely
/// by implementation-side expansion.
macro_rules! define_affiliate {
    (
        affiliate {
            $(#[$affiliate_meta:meta])*
            $affiliate:ident
        },

        counters {
            $(#[$counters_meta:meta])*
            $counters:ident
        },

        instance {
            $(#[$instance_meta:meta])*
            $instance:ident
        },

        bugs: $bugs:ident $(,)?
    ) => {
        paste::paste! {
            $(#[$affiliate_meta])*
            #[derive(Clone, Debug)]
            pub(crate) struct $affiliate;

            impl Transformation<ItemTrait> for $affiliate {
                fn raw_transform(
                    &self,
                    transform: &mut ItemTrait,
                    context: &(),
                ) -> Result<(), TokenStream> {
                    $counters::checked_extend(
                        &$counters,
                        transform,
                        context,
                    )?;

                    $instance::checked_extend(
                        &$instance,
                        transform,
                        context,
                    )?;

                    Ok(())
                }

                fn validate_transform(
                    &self,
                    transform: &ItemTrait,
                    context: Option<&()>,
                ) -> Result<(), TokenStream> {
                    $counters::validate_extend(
                        &$counters,
                        None,
                        transform,
                        context,
                    )?;

                    $instance::validate_extend(
                        &$instance,
                        None,
                        transform,
                        context,
                    )?;

                    Ok(())
                }
            }

            $(#[$counters_meta])*
            #[derive(Clone, Debug)]
            pub(crate) struct $counters;

            impl Extension<TraitItemType, ItemTrait>
                for $counters
            {
                fn raw_extend(
                    &self,
                    _towards: &ItemTrait,
                    _: &(),
                ) -> Result<TraitItemType, TokenStream> {

                    let ident = gen_type_ident::<$counters>();

                    Ok(TraitItemType {
                        attrs: proc_suite::internal_code(),
                        ident,
                        default: None,
                        type_token: Default::default(),
                        generics: Default::default(),
                        colon_token: Default::default(),
                        bounds: Default::default(),
                        semi_token: Default::default(),
                    })
                }

                fn validate_extend(
                    &self,
                    item: Option<&TraitItemType>,
                    towards: &ItemTrait,
                    _: Option<&()>,
                ) -> Result<(), TokenStream> {
                    let expected_ident = gen_type_ident::<Self>();
                    let bounds = &[];

                    validate_trait_type! {
                        item: item,
                        towards: towards,

                        ident: expected_ident,

                        bounds: bounds => {
                            not_found:
                                $bugs::[<$affiliate Counters Missing>] {},
                            wrong_ident:
                                $bugs::[<$affiliate Counters InvalidIdent>] {},
                            has_generics:
                                $bugs::[<$affiliate Counters HasGenerics>] {},
                            bound_not_found:
                                $bugs::[<$affiliate Counters BoundNotFound>] {},
                        }
                    }
                }
            }

            $(#[$instance_meta])*
            #[derive(Clone, Debug)]
            pub(crate) struct $instance;

            impl Extension<TraitItemType, ItemTrait>
                for $instance
            {
                fn raw_extend(
                    &self,
                    towards: &ItemTrait,
                    _: &(),
                ) -> Result<TraitItemType, TokenStream> {
                    let ident = gen_type_ident::<Self>();

                    let trait_ident = &towards.ident;

                    let counters_generic =
                        gen_type_ident::<InstanceTraitTypeNumCounters>();

                    let counters_assoc: syn::Type = {
                        let ident =
                            gen_type_ident::<$counters>();

                        parse_quote!(Self::#ident)
                    };

                    let args =
                        towards.generics.params.iter().map(|param| {
                            match param {
                                GenericParam::Type(ty) => {
                                    if ty.ident == counters_generic {
                                        GenericArgument::Type(
                                            counters_assoc.clone()
                                        )
                                    } else {
                                        let ident = &ty.ident;
                                        parse_quote!(#ident)
                                    }
                                }

                                GenericParam::Lifetime(lt) => {
                                    let lifetime = &lt.lifetime;
                                    parse_quote!(#lifetime)
                                }

                                GenericParam::Const(cnst) => {
                                    let ident = &cnst.ident;
                                    parse_quote!(#ident)
                                }
                            }
                        });

                    let mut angle : syn::AngleBracketedGenericArguments = parse_quote!(<#(#args),*>);

                    let mut collect = Vec::new();
                    for item in &towards.items {
                        let TraitItem::Type(ty) = item else {
                            continue;
                        };

                        if !ty.attrs.iter().any(|attr| attr.path().is_ident("sum")) {
                            continue;
                        }

                        let ty_ident = &ty.ident;

                        collect.push(ty_ident.clone());
                    }

                    for ident in &collect {
                        angle.args.push(parse_quote!(#ident = Self::#ident));
                    }

                    let bound = parse_quote!(
                        #trait_ident #angle
                    );

                    let mut bounds =
                        Punctuated::<TypeParamBound, Plus>::new();

                    bounds.push(TypeParamBound::Trait(bound));

                    Ok(TraitItemType {
                        attrs: proc_suite::internal_code(),
                        ident,
                        default: None,
                        type_token: Default::default(),
                        generics: Default::default(),
                        colon_token: Default::default(),
                        bounds,
                        semi_token: Default::default(),
                    })
                }

                fn validate_extend(
                    &self,
                    item: Option<&TraitItemType>,
                    towards: &ItemTrait,
                    _: Option<&()>,
                ) -> Result<(), TokenStream> {
                    let expected_ident = gen_type_ident::<Self>();

                    validate_trait_type! {
                        item: item,
                        towards: towards,

                        ident: expected_ident,

                        bounds: Vec::<&syn::TraitBound>::new() => {
                            not_found:
                                $bugs::[<$affiliate Instance Missing>] {},
                            wrong_ident:
                                $bugs::[<$affiliate Instance InvalidIdent>] {},
                            has_generics:
                                $bugs::[<$affiliate Instance HasGenerics>] {},
                            bound_not_found:
                                $bugs::[<$affiliate Instance BoundNotFound>] {},
                        }
                    }?;

                    let trait_ident = &towards.ident;

                    let counters_generic =
                        gen_type_ident::<InstanceTraitTypeNumCounters>();

                    let counters_assoc: syn::Type = {
                        let ident =
                            gen_type_ident::<$counters>();

                        parse_quote!(Self::#ident)
                    };

                    let args =
                        towards.generics.params.iter().map(|param| {
                            match param {
                                GenericParam::Type(ty) => {
                                    if ty.ident == counters_generic {
                                        GenericArgument::Type(
                                            counters_assoc.clone()
                                        )
                                    } else {
                                        let ident = &ty.ident;
                                        parse_quote!(#ident)
                                    }
                                }

                                GenericParam::Lifetime(lt) => {
                                    let lifetime = &lt.lifetime;
                                    parse_quote!(#lifetime)
                                }

                                GenericParam::Const(cnst) => {
                                    let ident = &cnst.ident;
                                    parse_quote!(#ident)
                                }
                            }
                        });

                    let mut angle : syn::AngleBracketedGenericArguments = parse_quote!(<#(#args),*>);

                    let mut collect = Vec::new();
                    for item in &towards.items {
                        let TraitItem::Type(ty) = item else {
                            continue;
                        };

                        if !ty.attrs.iter().any(|attr| attr.path().is_ident("sum")) {
                            continue;
                        }

                        let ty_ident = &ty.ident;

                        collect.push(ty_ident.clone());
                    }

                    for ident in &collect {
                        angle.args.push(parse_quote!(#ident = Self::#ident));
                    }


                    let sum_inst_item = towards.items.iter().find_map(|item| {
                        let TraitItem::Type(ty) = item else {
                            return None;
                        };

                        (ty.ident == expected_ident).then_some(ty)
                    });

                    let Some(sum_inst_item) = sum_inst_item else {
                        return Err($bugs::[<$affiliate Instance Missing>] {}.into());
                    };

                    let Some(trait_bound) = sum_inst_item.bounds.iter().find_map(|bound| {
                        let syn::TypeParamBound::Trait(bound) = bound else {
                            return None;
                        };

                        (bound.path.segments.last()?.ident == *trait_ident).then_some(bound)
                    }) else {
                        return Err($bugs::[<$affiliate Instance BoundNotFound>] {}.into());
                    };

                    let Some(segment) = trait_bound.path.segments.last() else {
                        return Err($bugs::[<$affiliate Instance BoundNotFound>] {}.into());
                    };

                    let syn::PathArguments::AngleBracketed(args) = &segment.arguments else {
                        return Err($bugs::[<$affiliate Instance BoundInvalid>] {}.into());
                    };

                    let expected_args = &angle.args;
                    let actual_args = &args.args;

                    if !(expected_args.len() <= actual_args.len()) {
                        return Err($bugs::[<$affiliate Instance BoundInvalid>] {}.into());
                    }

                    for (expected, actual) in expected_args.iter().zip(actual_args.iter()) {
                        if expected != actual {
                            return Err($bugs::[<$affiliate Instance BoundInvalid>] {}.into());
                        }
                    }

                    let actual_equalities = actual_args.iter().filter_map(|arg| {
                        let GenericArgument::AssocType(assoc) = arg else {
                            return None;
                        };

                        Some(assoc)
                    });

                    for ident in &collect {
                        let expected_type: Type = parse_quote!(Self::#ident);

                        let Some(_) = actual_equalities.clone().find(|assoc| {
                            assoc.ident == *ident && assoc.ty == expected_type
                        }) else {
                            return Err($bugs::[<$affiliate Instance BoundInvalid>] {}.into());
                        };
                    }

                    Ok(())

                }
            }
        }
    };
}

