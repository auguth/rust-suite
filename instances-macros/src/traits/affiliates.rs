/// Applies all affiliate families to a trait definition.
///
/// Affiliates allow one trait instance to reference *other* instances of the
/// same trait on the same `Self` type.
///
/// ```ignore
/// <Self as MyTrait<(U0, U0, U5)>>::NextAffiliateInstance
/// ```
///
/// behaves like:
///
/// ```ignore
/// MyTrait<(U0, U0, U6)>
/// ```
///
/// while:
///
/// ```ignore
/// <Self as MyTrait<(U0, U0, U5)>>::ReverseAffiliateInstance
/// ```
///
/// behaves like:
///
/// ```ignore
/// MyTrait<(U0, U0, U4)>
/// ```
///
/// This transformation injects the hidden associated items required for
/// affiliate-based instance navigation.
///
/// Generated items include:
///
/// - affiliate counter projections,
/// - affiliate instance projections,
///
/// ## Affiliate Families
///
/// - [`ReverseAffiliate`]
///     Structural reverse projection.
///
/// - [`CeilAffiliate`]
///     Structural jump-table / canonicalization projection.
///
/// - [`NextAffiliate`]
///     Semantic successor projection.
///
/// - [`BackAffiliate`]
///     Semantic predecessor projection.
///
/// - [`FloorAffiliates`]
///     Semantic canonical representatives / floor projections (per counter).
///
/// - [`AffiliateCountersChecker`]
///     Invariants Checker for rogue instance impls.
///
/// ## Sum-Type Relationships
///
/// Affiliate instance projections preserve the associated-type equality
/// relationships established by [`crate::traits::sum`].
///
/// When an affiliated instance is reconstructed, every `#[sum]` associated
/// type is carried into that instance as an explicit associated-type equality:
///
/// ```ignore
/// MyTrait<AffiliateCounters, Value = Self::Value>
/// ```
///
/// See the module-level documentation for more information about:
///
/// - affiliate semantics,
/// - structural vs semantic affiliates,
/// - and recursive instance navigation.
#[derive(Clone, Debug)]
pub(crate) struct InstanceTraitAffiliates;

impl Insertion<ItemTrait> for TraitItemType {
    fn raw_insert(&self, to: &mut ItemTrait, _: &()) -> Result<(), TokenStream> {
        to.items.push(TraitItem::Type(self.clone()));
        Ok(())
    }

    fn validate_inserted(
        _: Option<&Self>,
        _: &ItemTrait,
        _: Option<&()>,
    ) -> Result<(), TokenStream> {
        // We don't want to test syn internals
        Ok(())
    }
}

impl<'a> Transformation<ItemTrait, CounterParamsSlice<'a>> for InstanceTraitAffiliates {
    fn raw_transform(
        &self,
        transform: &mut ItemTrait,
        context: &CounterParamsSlice<'a>,
    ) -> Result<(), TokenStream> {
        ReverseAffiliate::checked_transform(&ReverseAffiliate, transform, &())?;
        CeilAffiliate::checked_transform(&CeilAffiliate, transform, &())?;
        NextAffiliate::checked_transform(&NextAffiliate, transform, &())?;
        BackAffiliate::checked_transform(&BackAffiliate, transform, &())?;
        FloorAffiliates::checked_transform(&FloorAffiliates, transform, context)?;
        AffiliateCountersChecker::checked_extend(&AffiliateCountersChecker, transform, &())?;
        Ok(())
    }

    fn validate_transform(
        &self,
        transform: &ItemTrait,
        context: Option<&CounterParamsSlice<'a>>,
    ) -> Result<(), TokenStream> {
        ReverseAffiliate::validate_transform(&ReverseAffiliate, transform, None)?;
        CeilAffiliate::validate_transform(&CeilAffiliate, transform, None)?;
        NextAffiliate::validate_transform(&NextAffiliate, transform, None)?;
        BackAffiliate::validate_transform(&BackAffiliate, transform, None)?;
        FloorAffiliates::validate_transform(&FloorAffiliates, transform, context)?;
        AffiliateCountersChecker::validate_extend(
            &AffiliateCountersChecker,
            None,
            transform,
            None,
        )?;
        Ok(())
    }
}

