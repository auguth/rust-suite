impl<'a> Extension<Vec<TraitItemType>, ItemTrait, CounterParamsSlice<'a>>
    for FloorAffiliatesInstances
{
    fn raw_extend(
        &self,
        towards: &ItemTrait,
        context: &CounterParamsSlice<'a>,
    ) -> Result<Vec<TraitItemType>, TokenStream> {
        let mut collect = Vec::new();
        for c in context.iter() {
            let gen_idx_str = c.generic_index.to_string();
            let gen_idx_byes = gen_idx_str.as_bytes();

            let ident = gen_type_ident_with_suffix::<Self>(Some(gen_idx_byes));

            let trait_ident = &towards.ident;

            let counters_generic = gen_type_ident::<InstanceTraitTypeNumCounters>();

            let counters_assoc: syn::Type = {
                let ident =
                    gen_type_ident_with_suffix::<FloorAffiliatesCounters>(Some(gen_idx_byes));

                parse_quote!(Self::#ident)
            };

            let args = towards.generics.params.iter().map(|param| match param {
                GenericParam::Type(ty) => {
                    if ty.ident == counters_generic {
                        GenericArgument::Type(counters_assoc.clone())
                    } else {
                        let ident = &ty.ident;

                        parse_quote!(#ident)
                    }
                }

                GenericParam::Lifetime(lt) => {
                    let lifetime = &lt.lifetime;

                    parse_quote!(#lifetime)
                }

                GenericParam::Const(cnst) => {
                    let ident = &cnst.ident;

                    parse_quote!(#ident)
                }
            });

            let mut angle: syn::AngleBracketedGenericArguments = parse_quote!(<#(#args),*>);

            let mut sums = Vec::new();
            for item in &towards.items {
                let TraitItem::Type(ty) = item else {
                    continue;
                };

                if !ty.attrs.iter().any(|attr| attr.path().is_ident("sum")) {
                    continue;
                }

                let ty_ident = &ty.ident;

                sums.push(ty_ident.clone());
            }

            for ident in &sums {
                angle.args.push(parse_quote!(#ident = Self::#ident));
            }

            let bound = parse_quote!(
                #trait_ident #angle
            );

            let mut bounds = Punctuated::<TypeParamBound, Plus>::new();

            bounds.push(TypeParamBound::Trait(bound));

            collect.push(TraitItemType {
                attrs: proc_suite::internal_code(),
                ident,
                default: None,
                type_token: Default::default(),
                generics: Default::default(),
                colon_token: Default::default(),
                bounds,
                semi_token: Default::default(),
            })
        }
        Ok(collect)
    }

    fn validate_extend(
        &self,
        item: Option<&Vec<TraitItemType>>,
        towards: &ItemTrait,
        context: Option<&CounterParamsSlice<'a>>,
    ) -> Result<(), TokenStream> {
        let extracted;
        let counters = match context {
            Some(c) => c,
            None => {
                extracted = CounterParams::checked_extract(towards, &None)?;
                extracted.as_slice().as_ref().as_ref()
            }
        };

        for c in counters.iter() {
            let gen_idx_str = c.generic_index.to_string();
            let gen_idx_byes = gen_idx_str.as_bytes();

            let expected_ident = gen_type_ident_with_suffix::<Self>(Some(gen_idx_byes));

            validate_trait_types! {
                items: item,
                towards: towards,

                ident: expected_ident,

                bounds: Vec::<&syn::TraitBound>::new() => {
                    not_found:
                        AffiliateBugs::
                            FloorAffiliatesInstancesMissing {},
                    wrong_ident:
                        AffiliateBugs::
                            FloorAffiliatesInstancesInvalidIdent {},
                    has_generics:
                        AffiliateBugs::
                            FloorAffiliatesInstancesHasGenerics {},
                    bound_not_found:
                        AffiliateBugs::
                            FloorAffiliatesInstancesBoundNotFound {},
                }
            };

            let trait_ident = &towards.ident;

            let counters_generic = gen_type_ident::<InstanceTraitTypeNumCounters>();

            let counters_assoc: syn::Type = {
                let ident =
                    gen_type_ident_with_suffix::<FloorAffiliatesCounters>(Some(gen_idx_byes));

                parse_quote!(Self::#ident)
            };

            let args = towards.generics.params.iter().map(|param| match param {
                GenericParam::Type(ty) => {
                    if ty.ident == counters_generic {
                        GenericArgument::Type(counters_assoc.clone())
                    } else {
                        let ident = &ty.ident;

                        parse_quote!(#ident)
                    }
                }

                GenericParam::Lifetime(lt) => {
                    let lifetime = &lt.lifetime;

                    parse_quote!(#lifetime)
                }

                GenericParam::Const(cnst) => {
                    let ident = &cnst.ident;

                    parse_quote!(#ident)
                }
            });

            let mut angle: syn::AngleBracketedGenericArguments = parse_quote!(<#(#args),*>);

            let mut collect = Vec::new();
            for item in &towards.items {
                let TraitItem::Type(ty) = item else {
                    continue;
                };

                if !ty.attrs.iter().any(|attr| attr.path().is_ident("sum")) {
                    continue;
                }

                let ty_ident = &ty.ident;

                collect.push(ty_ident.clone());
            }

            for ident in &collect {
                angle.args.push(parse_quote!(#ident = Self::#ident));
            }

            let sum_inst_item = towards.items.iter().find_map(|item| {
                let TraitItem::Type(ty) = item else {
                    return None;
                };

                (ty.ident == expected_ident).then_some(ty)
            });

            let Some(sum_inst_item) = sum_inst_item else {
                return Err(AffiliateBugs::FloorAffiliatesInstancesMissing {}.into());
            };

            let Some(trait_bound) = sum_inst_item.bounds.iter().find_map(|bound| {
                let syn::TypeParamBound::Trait(bound) = bound else {
                    return None;
                };

                (bound.path.segments.last()?.ident == *trait_ident).then_some(bound)
            }) else {
                return Err(AffiliateBugs::FloorAffiliatesInstancesBoundNotFound {}.into());
            };

            let Some(segment) = trait_bound.path.segments.last() else {
                return Err(AffiliateBugs::FloorAffiliatesInstancesBoundNotFound {}.into());
            };

            let syn::PathArguments::AngleBracketed(args) = &segment.arguments else {
                return Err(AffiliateBugs::FloorAffiliatesInstancesBoundInvalid {}.into());
            };

            let expected_args = &angle.args;
            let actual_args = &args.args;

            if !(expected_args.len() <= actual_args.len()) {
                return Err(AffiliateBugs::FloorAffiliatesInstancesBoundInvalid {}.into());
            }

            for (expected, actual) in expected_args.iter().zip(actual_args.iter()) {
                if expected != actual {
                    return Err(AffiliateBugs::FloorAffiliatesInstancesBoundInvalid {}.into());
                }
            }

            let actual_equalities = actual_args.iter().filter_map(|arg| {
                let GenericArgument::AssocType(assoc) = arg else {
                    return None;
                };

                Some(assoc)
            });

            for ident in &collect {
                let expected_type: Type = parse_quote!(Self::#ident);

                let Some(_) = actual_equalities
                    .clone()
                    .find(|assoc| assoc.ident == *ident && assoc.ty == expected_type)
                else {
                    return Err(AffiliateBugs::FloorAffiliatesInstancesBoundInvalid {}.into());
                };
            }
        }
        Ok(())
    }
}

