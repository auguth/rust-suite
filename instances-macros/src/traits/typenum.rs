//! Rewrites extracted instance-counter const generics into the synthesized
//! [`InstanceTraitTypeNumCounters`] type parameter.
//!
//! This transformation removes all extracted counter const generics from an
//! [`ItemTrait`] while preserving all other generics unchanged. The resulting
//! type-level representation is used by later expansion stages to perform
//! instance-counter computation through typenum-based machinery on stable Rust.
//!
//! ## Example
//!
//! Given:
//!
//! ```ignore
//! #[trait_instance(A, C)]
//! trait Example<const A: u8, const B: usize, const C: u8> {}
//! ```
//!
//! extraction identifies:
//!
//! ```text
//! A, C
//! ```
//!
//! and this transformation rewrites the trait into:
//!
//! ```ignore
//! trait Example<__TypeNumCounters, const B: usize> {}
//! ```
//!
//! where `__TypeNumCounters` is an internal synthesized type parameter
//! generated by the [`InstanceTraitTypeNumCounters`] [`Transformation`] pass.

// ===============================================================================
// ``````````````````````````````````` IMPORTS ```````````````````````````````````
// ===============================================================================

