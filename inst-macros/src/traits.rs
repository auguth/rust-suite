/// Transforms instance-node associated types declared on an instance trait.
///
/// Each `#[node(...)]` attribute is parsed as a [`BoundInstance`], its
/// instance-trait bound is resolved, and the instance model is lowered into
/// [`NodeArgs`]. The resulting node arguments are attached as an internal
/// `#[instance_sub(...)]` attribute annotation consumed by delegated attribute macro
/// `instance_node_explicit_target`.
///
/// `#[node(...)]` is only valid on associated types; constants and functions
/// cannot declare instance nodes.
///
/// The `instance_node_explicit_target` attribute is then added to the trait,
/// and [`SupportCrate::delegate_attribute`] appends the delegate macro for
/// the final transformation by [`crate::delegate_support_crate_internal_only`].
///
/// Before transformation:
///
/// ```ignore
/// #[node(Crypto::Hasher(Module, Function))]
/// type Hash;
/// ```
///
/// After this phase:
///
/// ```ignore
/// #[instance_sub(...)]
/// type Hash;
///
/// // and on the trait
///
/// #[support_crate::instance_node_explicit_target]
/// #[support_crate::delegate_support_crate_internal_only]
/// trait Hasher { ... }
/// ```
///
/// The transformation of the node arguments is performed separately from the
/// trait generic-header transformation, but both phases are unified by the
/// [`TraitInst`] pipeline.
#[derive(Debug, Clone)]
struct ItemTypeNodeInst;

impl Transformation<ItemTrait> for ItemTypeNodeInst {
    fn raw_transform(
        &self,
        transform: &mut ItemTrait,
        _: &(),
    ) -> Result<(), proc_macro2::TokenStream> {
        let node = Inst::node();

        let mut ty_items = Vec::new();
        for item in &mut transform.items {
            if let TraitItem::Type(t) = item {
                if t.attrs.iter().any(|attr| attr.path().is_ident(&node)) {
                    ty_items.push(t);
                }
            }
        }

        for ty in ty_items {
            let mut node_attr = None;
            let mut build = Vec::new();
            for attr in &ty.attrs {
                if !attr.path().is_ident(&node) {
                    build.push(attr.clone());
                    continue;
                }
                if node_attr.is_some() {
                    return Err(TraitError::DoubleNode { attr: attr.clone() }.into());
                };
                node_attr = Some(attr.clone());
            }
            ty.attrs = build;
            let Some(node_attr) = node_attr else {
                return Err(TraitBug::InconsistencyFindingNodeAttribute {}.into());
            };

            let tokens = match &node_attr.meta {
                syn::Meta::List(meta_list) => &meta_list.tokens,
                syn::Meta::Path(_) => {
                    return Err(TraitError::NodeRequiresArgs {
                        attr: node_attr.clone(),
                    }
                    .into());
                }
                syn::Meta::NameValue(meta) => {
                    return Err(TraitError::NodeRequiresArgsNotValue { meta: meta.clone() }.into());
                }
            };
            if tokens.is_empty() {
                return Err(TraitError::NodeRequiresArgs {
                    attr: node_attr.clone(),
                }
                .into());
            }

            let inst = BoundInstance::checked_extract(tokens, &())?;

            let indexes = append_placeholder_args(&mut ty.bounds, &inst.path, &inst.bound, true)?;

            let node_args = NodeArgs::checked_extract(&inst.bound, &indexes)?;

            let attrs = &mut ty.attrs;

            let sub_target = Inst::subscriber();
            attrs.insert(0, parse_quote!(#[#sub_target(#node_args)]));

            cfg_feature_disclaimer(ty);
        }

        let attrs = &mut transform.attrs;
        let support_crate = Inst::support_crate();
        let node_target = Inst::node_target();
        attrs.insert(
            0,
            parse_quote!(#[#support_crate::#node_target]),
        );
        Inst::delegate_attribute(attrs);

        Ok(())
    }

    fn validate_transform(
        &self,
        transform: &ItemTrait,
        _: Option<&()>,
    ) -> Result<(), proc_macro2::TokenStream> {
        let support_crate = Inst::support_crate();
        let Some(delegate_macro) = Inst::delegate_macro() else {
            return Err(TraitBug::DelegateMacroNotInitialized {}.into());
        };

        let Some((idx, inst_attr)) = transform.attrs.iter().enumerate().find_map(|(i, attr)| {
            let node_target = Inst::node_target();
            if *attr.path() == parse_quote!(#support_crate::#node_target) {
                return Some((i, attr));
            }
            return None;
        }) else {
            return Err(TraitBug::InstanceTraitNodeMacroNotFound {}.into());
        };

        if !transform.attrs.iter().enumerate().any(|(i, attr)| {
            if i <= idx {
                return false;
            }
            *attr.path() == parse_quote!(#support_crate::#delegate_macro)
        }) {
            return Err(TraitBug::DelegateMacroNotFound {}.into());
        }

        let syn::Meta::Path(_) = &inst_attr.meta else {
            return Err(TraitBug::InstanceTraitNodeMacroArgsFound {}.into());
        };

        let node = Inst::node();

        for item in &transform.items {
            match item {
                TraitItem::Const(c) => {
                    if c.attrs.iter().any(|attr| attr.path().is_ident(&node)) {
                        return Err(TraitBug::NodeOnlyInTypeAssoc {}.into());
                    }
                }
                TraitItem::Fn(f) => {
                    if f.attrs.iter().any(|attr| attr.path().is_ident(&node)) {
                        return Err(TraitBug::NodeOnlyInTypeAssoc {}.into());
                    }
                }
                TraitItem::Type(ty) => {
                    if !ty
                        .attrs
                        .iter()
                        .any(|attr| attr.path().is_ident(&Inst::subscriber()))
                    {
                        continue;
                    }
                    // rest validation requires re-parsing which is not required
                }
                _ => {}
            }
        }

        Ok(())
    }
}

