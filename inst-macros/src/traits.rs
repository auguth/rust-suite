/// A trait-bound is matched against `path`. The matching trait bound is removed,
/// its instance arguments are appended after lifetime arguments, and the
/// transformed bound is inserted at the beginning of the bounds list.
///
/// If `push_args` is `true`, each instance parameter position receives a
/// placeholder const argument (`0`). If `false`, only the positions are
/// calculated and returned.
///
/// Before:
///
/// ```ignore
/// T: Crypto::Hasher + Send
/// ```
///
/// After with `bound = (Module, Function)` and `push_args = true`:
///
/// ```ignore
/// T: Crypto::Hasher<0, 0> + Send
/// ```
///
/// The returned [`IntList`] contains the generic argument positions of the
/// inserted instance counters.
pub fn append_placeholder_args(
    bounds: &mut Punctuated<TypeParamBound, Plus>,
    path: &Punctuated<Ident, PathSep>,
    bound: &InstanceModel,
    push_args: bool,
) -> Result<IntList, TokenStream> {
    let mut found = None;
    let mut build = Punctuated::<TypeParamBound, Plus>::new();

    for t_bound in bounds.iter() {
        let TypeParamBound::Trait(trait_) = t_bound else {
            build.push(t_bound.clone());
            continue;
        };

        let trait_path = trait_.path.segments.iter().map(|seg| &seg.ident).rev();
        let asked = path.iter().rev();

        if asked.len() != trait_path.len() {
            build.push(t_bound.clone());
            continue;
        }

        if asked.zip(trait_path).all(|(given, orig)| given == orig) {
            if found.is_some() {
                return Err(TraitError::DuplicateInstanceTraitBound {
                    bound: trait_.clone(),
                }
                .into());
            }

            found = Some(trait_.clone());
            continue;
        }

        build.push(t_bound.clone());
    }

    *bounds = build;

    let Some(mut trait_bound) = found else {
        return Err(TraitError::ExpectedInstTraitNodeBound {
            bounds: bounds.clone(),
            exp: path.clone(),
        }
        .into());
    };

    let indexes = append_placeholder_args_to_trait(&mut trait_bound.path, bound, push_args)?;

    bounds.insert(0, TypeParamBound::Trait(trait_bound));

    Ok(indexes)
}

/// Appends placeholder instance arguments to an instance-trait path.
///
/// The instance arguments are inserted after all lifetime arguments. One
/// position is produced for each parameter in the [`InstanceModel`].
///
/// With `push_args` enabled, a `0` const argument is inserted at each
/// position; otherwise only the positions are returned.
///
/// ```ignore
/// Crypto::Hasher<'a, T>
/// ```
///
/// with two instance parameters becomes:
///
/// ```ignore
/// Crypto::Hasher<'a, 0, 0, T>
/// ```
///
/// The returned [`IntList`] contains the positions at which the instance
/// arguments were inserted.
pub fn append_placeholder_args_to_trait(
    path: &mut syn::Path,
    bound: &InstanceModel,
    push_args: bool,
) -> Result<IntList, TokenStream> {
    let args = &mut path.segments.last_mut().unwrap().arguments;

    let angle = match args {
        PathArguments::None => {
            *args = PathArguments::AngleBracketed(AngleBracketedGenericArguments {
                colon2_token: Default::default(),
                lt_token: Default::default(),
                args: Default::default(),
                gt_token: Default::default(),
            });

            let PathArguments::AngleBracketed(angle) = args else {
                unreachable!()
            };

            angle
        }

        PathArguments::AngleBracketed(angle) => angle,

        PathArguments::Parenthesized(paren) => {
            return Err(TraitError::ParenthesizedInstTraitNodeBound {
                paren: paren.clone(),
            }
            .into());
        }
    };

    // Only append params after lifetimes.
    let mut seen_non_lifetime = false;

    for param in angle.args.iter() {
        if let GenericArgument::Lifetime(lt) = param {
            if seen_non_lifetime {
                return Err(ProcParseErr::LifetimeShouldBeDeclaredFront { lt: lt.clone() }.into());
            }
        } else {
            seen_non_lifetime = true;
        }
    }

    let index = angle
        .args
        .iter()
        .position(|param| !matches!(param, GenericArgument::Lifetime(_)))
        .unwrap_or(angle.args.len());

    let mut indexes = IntList::default();

    for offset in 0..InstModelLength::checked_extract(bound, &())?.0 {
        let offsetted = index + offset;

        if push_args {
            angle
                .args
                .insert(offsetted, GenericArgument::Const(parse_quote!(0)));
        }

        indexes
            .ints
            .push(LitInt::new(&offsetted.to_string(), Span::call_site()));
    }

    if angle.args.is_empty() {
        *args = PathArguments::None;
    }

    Ok(indexes)
}

/// Prepends a inst cfg feature documentation disclaimer.
pub fn cfg_feature_disclaimer<T: InsertDocs>(item: &mut T) {
    item.prepend_docs(vec![
        DocAttr::Raw(
            "*Note: This is an internal expansion of `cfg(feature = \"inst\")`*"
                .to_string(),
        ),
        DocAttr::Bullet {
            level: 0,
            content: vec![DocAttr::Raw(
                "This may include internal proc-macro expansions which should not be used in user scope as it may be susceptible to change."
                    .to_string(),
            )],
        },
        DocAttr::Bullet {
            level: 0,
            content: vec![DocAttr::Raw(
                "For authoritative documentation, rely on plain generated rustdoc (`cargo doc`) or docs.rs output."
                    .to_string(),
            )],
        },
        DocAttr::Bullet {
            level: 0,
            content: vec![DocAttr::Raw(
                "For build, rely on feature `cargo build --features inst` output."
                    .to_string(),
            )],
        },
        DocAttr::LineBreak,
    ]);
}
