/// Transforms an instance trait through the [`crate::inst`] macro pipeline.
///
/// An instance trait declares named instance parameters, which are lowered
/// into const generic instance counters. Instance-node associated types,
/// instance sum types are also transformed into their 
/// generated representations.
///
/// Before transformation:
///
/// ```ignore
/// #[inst(Module, Function)]
/// trait Hasher {
///     #[node(..)]
///     type Hash;
///
///     #[sum]
///     type Output;
/// }
/// ```
///
/// The source trait is transformed into an internal `cfg(not(feature = "int"))` form.
/// The [`SupportCrate`] provides the public crate path, which re-exports the
/// explicit macro entry points from the `instances-macro` crate. Generated
/// attributes therefore reference those macros through the support crate:
///
/// ```ignore
/// #[cfg(not(feature = "inst"))]
/// #[support_crate::instance_trait_explicit_target(0, 1)]
/// #[support_crate::instance_node_explicit_target]
/// trait Hasher<const __INST_0: u8, const __INST_1: u8> {
///     #[instance_sub(...)]
///     type Hash;
/// 
///     type Output;
/// }
/// ```
///
/// The transformation of the trait header generics and the transformation
/// of `#[node(...)]` associated types are separate transformation phases.
/// 
/// They are independently applied and validated, but are unified as part of
/// the same [`TraitInst`] macro pipeline.
///
/// A separate `cfg(not(feature = "inst"))` copy is retained for rustdoc 
/// and contains the generated documentation for the instance trait, 
/// its instance nodes, and its instance sum types:
///
/// ```ignore
/// #[cfg(not(feature = "inst"))]
/// /// Documentation Disclaimer for Instance Traits
/// trait Hasher {
///     /// Documentation Disclaimer for Instance Nodes
///     type Hash;
/// }
/// ```
///
/// The documentation representation intentionally hides the generated
/// instance-counter generics. The public trait interface is documented in
/// terms of the instance macros provided by this crate; the generated
/// implementation form is an internal expansion detail.
///
/// Thus, the expanded implementation is used when `inst` is enabled,
/// while the documentation-oriented copy is used when `inst` is not enabled.
/// The transformation also adds the metadata required for delegated macro
/// expansion.
#[derive(Debug, Clone)]
pub struct TraitInst;

impl Transformation<File, TokenStream> for TraitInst {
    fn raw_transform(
        &self,
        transform: &mut File,
        context: &TokenStream,
    ) -> Result<(), proc_macro2::TokenStream> {
        if transform.items.len() > 1 {
            return Err(ParseBug::TooManyItemsToTransform {}.into());
        }
        let Some(Item::Trait(trait_)) = transform
            .items
            .iter_mut()
            .find(|item| matches!(item, Item::Trait(_)))
        else {
            return Err(TraitBug::FileContainsNoTrait {}.into());
        };
        let idents = match context.is_empty() {
            true => None,
            false => {
                let idents = IdentList::checked_extract(context, &())?;
                Some(idents)
            }
        };

        let mut doc_trait = trait_.clone();
        let mut addon = File {shebang: None, attrs: Vec::new(), items: Vec::new()};

        ItemTypeInst::checked_transform(&ItemTypeInst, &mut (&mut addon, trait_), &idents)?;
        if let Some(idents) = &idents {
            TraitGenericsInst::checked_transform(&TraitGenericsInst, trait_, idents)?;
        }
        cfg_feature_disclaimer(&mut trait_.attrs);
        trait_.attrs.insert(0, Inst::feature());

        for item in addon.items {
            transform.items.push(item);
        }

        TraitInstDoc::checked_transform(&TraitInstDoc, &mut doc_trait, &idents)?;
        doc_trait.attrs.insert(0, Inst::not_feature());
        transform.items.push(Item::Trait(doc_trait));

        Ok(())
    }

    fn validate_transform(
        &self,
        transform: &File,
        context: Option<&TokenStream>,
    ) -> Result<(), proc_macro2::TokenStream> {
        let find = |doc: bool, item: &Item| -> bool {
            let Item::Trait(trait_) = item else {
                return false;
            };
            trait_.attrs.iter().any(|attr| {
                if *attr == Inst::feature() {
                    if doc {false} else {true}
                } else if *attr == Inst::not_feature() {
                    if doc {true} else {false}

                } else {
                    false
                }
            }) 
        };
        let Some(doc_trait) = transform.items.iter().find(|item| find(true, item)) else {
            return Err(TraitBug::TransformedFileDoesNotHaveDocTarget {}.into());
        };
        let Some(not_doc_trait) = transform.items.iter().find(|item| find(false, item)) else {
            return Err(TraitBug::TransformedFileDoesNotHaveNotDocTarget {}.into());
        };

        let Item::Trait(trait_) = not_doc_trait else {
            unreachable!()
        };
        if !trait_.clone().has_docs() {
            return Err(TraitBug::NotDocTargetDoesNotHaveDocs {}.into());
        }

        if let Some(context) = context {
            if !context.is_empty() {
                let Item::Trait(trait_) = doc_trait else {
                    unreachable!()
                };
                if !trait_.clone().has_docs() {
                    return Err(TraitBug::DocTargetDoesNotHaveDocs {}.into());
                }
            }
        }

        Ok(())
    }
}

