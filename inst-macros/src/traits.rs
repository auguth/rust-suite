/// Transforms an instance trait into its documentation representation.
///
/// This transformation is applied to the `cfg(not(feature = "inst"))` copy produced by
/// [`TraitInst`]. It removes the internal `#[node(...)]`, `#[sum]` 
/// attributes and replaces them with generated rustdoc describing the
/// instance nodes and instance sum types.
///
/// For an instance trait, it also adds a trait-level description containing
/// its declared instance parameters and points users to the [`crate::inst`]
/// macros used to define and access instance traits.
///
/// Before transformation:
///
/// ```ignore
/// #[inst(Module, Function)]
/// trait Hasher {
///     #[node(Node(..))]
///     type Hash: Node;
///
///     #[sum]
///     type Output;
/// }
/// ```
///
/// The documentation representation retains the user-facing trait while
/// replacing the instance-specific attributes with documentation:
///
/// ```ignore
/// /// # Instance Trait `(Module, Function)`
/// ///
/// /// An instance trait such as `Hasher` is implemented using
/// /// `#[inst(..)]` and its trait items are accessed through
/// /// `inst_get!()` or `inst_direct!()`.
/// trait Hasher {
///     /// # Instance Node [`Node`]
///     ///
///     /// An instance node associated accessed through `inst_get!()`.
///     type Hash;
///     
///     /// # Instance Sum Type [`Hasher`]
///     ///
///     /// An instance sum type is interoperable across dynamic instances.
///     type Output;
/// }
/// ```
///
/// When no instance parameters are supplied, the transformation does not
/// permit `#[sum]` associated types, since instance sum types are only valid
/// for instance traits.
#[derive(Debug, Clone)]
pub struct TraitInstDoc;

impl Transformation<ItemTrait, Option<IdentList>> for TraitInstDoc {
    fn raw_transform(
        &self,
        transform: &mut ItemTrait,
        context: &Option<IdentList>,
    ) -> Result<(), proc_macro2::TokenStream> {
        let ident = transform.ident.clone();

        if let Some(idents) = context {
            transform.attrs.prepend_docs(vec![
                DocAttr::Heading {
                    level: 0,
                    content: vec![DocAttr::Raw(format!(
                        "Instance Trait `({})`",
                        idents.to_token_stream()
                    ))],
                },
                DocAttr::Raw(format!(
                    "An instance trait such as `{}` is implemented using ",
                    ident,
                )),
                DocAttr::Link {
                    title: "#[inst(..)]".to_string(),
                    url: "inst::inst".to_string(),
                },
                DocAttr::Raw(" and its trait items are accessed through ".to_string()),
                DocAttr::Link {
                    title: "inst_get!()".to_string(),
                    url: "inst::inst_get".to_string(),
                },
                DocAttr::Raw(" *or* ".to_string()),
                DocAttr::Link {
                    title: "inst_direct!()".to_string(),
                    url: "inst::inst_direct".to_string(),
                },
                DocAttr::Raw(".".to_string()),
                DocAttr::LineBreak,
                DocAttr::Raw("*See* ".to_string()),
                DocAttr::Link {
                    title: "`inst::trait`".to_string(),
                    url: "inst::trait".to_string(),
                },
                DocAttr::Raw(" *for instance trait definitions,* ".to_string()),
                DocAttr::Link {
                    title: "`inst::impl`".to_string(),
                    url: "inst::impl".to_string(),
                },
                DocAttr::Raw(" *for instance implementations.*".to_string()),
                DocAttr::LineBreak,
            ]);
        }

        for item in &mut transform.items {
            let TraitItem::Type(ty) = item else {
                continue;
            };

            let mut docs = Vec::new();
            let mut node = None;
            let mut is_sum = false;

            let attrs = std::mem::take(&mut ty.attrs);
            let mut retained_attrs = Vec::with_capacity(attrs.len());

            let node_ident = Inst::node();
            let sum_ident = Inst::sum();

            for attr in attrs {
                let path_ident = attr.path().get_ident();

                match path_ident {
                    Some(ident) if *ident == node_ident => {
                        let tokens = match &attr.meta {
                            syn::Meta::List(meta_list) => &meta_list.tokens,
                            syn::Meta::Path(_) => {
                                return Err(TraitBug::NodeRequiresArgs {}.into());
                            }
                            syn::Meta::NameValue(_) => {
                                return Err(TraitBug::NodeRequiresArgsNotValue {}.into());
                            }
                        };

                        if tokens.is_empty() {
                            return Err(TraitBug::NodeRequiresArgs {}.into());
                        }

                        node = Some(BoundInstance::checked_extract(tokens, &())?);
                    }
                    Some(ident) if *ident == sum_ident => {
                        if context.is_none() {
                            return Err(TraitError::SumNotAllowed { attr }.into());
                        }

                        if !matches!(&attr.meta, syn::Meta::Path(_)) {
                            return Err(TraitError::SumNoArgs { attr }.into());
                        }

                        is_sum = true;
                    }

                    _ => retained_attrs.push(attr),
                } 
            }

            ty.attrs = retained_attrs;

            if let Some(bound) = node {
                let path = bound.path.to_token_stream().to_string();

                docs.extend([
                    DocAttr::Heading {
                        level: 1,
                        content: vec![
                            DocAttr::Raw("Instance Node ".to_string()),
                            DocAttr::Ref(path),
                            DocAttr::Raw(format!("`{}`", bound.bound.to_token_stream())),
                        ],
                    },
                    DocAttr::Raw("An instance node associated accessed through ".to_string()),
                    DocAttr::Link {
                        title: "inst_get!()".to_string(),
                        url: "inst::inst_get".to_string(),
                    },
                    DocAttr::Raw(".".to_string()),
                    DocAttr::LineBreak,
                    DocAttr::Raw("*See* ".to_string()),
                    DocAttr::Link {
                        title: "`inst::node`".to_string(),
                        url: "inst::node".to_string(),
                    },
                    DocAttr::Raw(" *for instance node definitions and syntax.*".to_string()),
                    DocAttr::LineBreak,
                ]);
            }

            if is_sum {
                docs.extend([
                    DocAttr::Heading {
                        level: 1,
                        content: vec![
                            DocAttr::Raw("Instance Sum Type ".to_string()),
                            DocAttr::Ref(ident.to_string()),
                        ],
                    },
                    DocAttr::Raw(
                        "An instance sum type is interoperable across \
                         dynamic instances."
                            .to_string(),
                    ),
                    DocAttr::LineBreak,
                    DocAttr::Raw("*See* ".to_string()),
                    DocAttr::Link {
                        title: "`inst::sum`".to_string(),
                        url: "inst::sum".to_string(),
                    },
                    DocAttr::Raw(" *for instance sum type definitions.*".to_string()),
                    DocAttr::LineBreak,
                ]);
            }

            ty.attrs.prepend_docs(docs);
        }

        Ok(())
    }

    fn validate_transform(
        &self,
        transform: &ItemTrait,
        context: Option<&Option<IdentList>>,
    ) -> Result<(), proc_macro2::TokenStream> {
        if let Some(Some(_)) = context {
            if !&transform.attrs.clone().has_docs() {
                return Err(TraitBug::TraitDocsNotFound {}.into());
            }
        }

        for item in &transform.items {
            let TraitItem::Type(ty) = item else {
                continue;
            };
            if ty.attrs.iter().any(|attr| attr.path().is_ident(&Inst::sum())) {
                return Err(TraitBug::DocTargetInstTraitSumAttrExists {}.into());
            }
            if ty.attrs.iter().any(|attr| attr.path().is_ident(&Inst::node())) {
                return Err(TraitBug::DocTargetInstTraitNodeAttrExists {}.into());
            }
        }
        Ok(())
    }
}

