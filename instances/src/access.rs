// ``````````````````````````````` TERMINAL ACCESS ```````````````````````````````
// ===============================================================================

/// Resolves the counter tuple associated with the uniquely identified
/// terminal instance impl implemented towards `SelfTy`.
///
/// Unlike other access traits, `TerminalAccess` requires no identifier hash
/// sequence or counter-context generic arguments. The terminal instance is
/// unique for the contextual instance type, so `SelfTy` alone is sufficient
/// to select its generated access-trait implementation.
///
/// The associated `Terminal` type is the complete typenum counter tuple
/// associated with the resolved terminal instance. Its elements represent the
/// counters for the terminal instance's dimensions.
///
/// For example, a terminal access implementation may provide:
///
/// ```ignore
/// impl TerminalAccess<InstanceType> for Global {
///     type Terminal = (U2, U4);
/// }
/// ```
///
/// The counter tuple can then be recovered through the associated-type
/// projection:
///
/// ```ignore
/// <Global as TerminalAccess<InstanceType>>::Terminal
/// ```
///
/// `TerminalAccess` therefore provides a unique access path to the terminal
/// instance's complete counter context without requiring any identifier
/// sequence or explicit counter dimensions.
pub trait TerminalAccess<SelfTy: ?Sized> {
    type Terminal: Marker;
}

