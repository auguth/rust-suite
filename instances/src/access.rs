//! Internal access traits used by the instances system to carry and recover
//! compile-time metadata across generated instance implementations.
//!
//! This module defines the type-level access interfaces used by the
//! [`crate`] re-exported proc-macros to communicate instance metadata through Rust's trait
//! system. The access traits identify generated instance metadata by
//! identifier hashes, contextual instance types, counter positions, and other
//! compile-time parameters, allowing later generated code to recover metadata
//! without revisiting the original instance definition.
//!
//! The access interfaces are implementation details of the instances macros
//! and are intended to be used only by generated code produced by those macros.
//! They are not intended for direct use by library users or by unrelated parts
//! of the crate.
//!
//! The traits are public only where required so that generated implementations
//! and generated access sites can cross the visibility boundaries imposed by
//! Rust's type system. Their public visibility should therefore not be
//! interpreted as a stable API guarantee.
//!
//! The signatures of these traits may change as the instances system evolves.
//! Code outside the generated instances machinery should not depend on their
//! names, generic parameter ordering, associated types, or other signature
//! details.
//!
//! The module currently provides access to:
//!
//! - `CounterAccess` - Complete counter tuple for an identified instance.
//! - `TerminalAccess` - Complete counter tuple for the terminal instance.
//! - `BoundaryAccess` - Boundary counter tuple and final identifier hash.
//! - `OnSetAccess` - Boundary counter tuple and initial identifier hash.
//! - `IdentHashLenAccess` - Identifier length associated with a counter generic position.
//!
//! All metadata exposed through these interfaces is resolved at compile time
//! through trait implementations generated by the instances macros.

