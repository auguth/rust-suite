///
/// For example:
///
/// ```text
/// identifier path:
///     A, B, C, D
///
/// generic index:
///     0    1    2    3
///
/// identifier length:
///     3    5    7    9
/// ```
///
/// Selecting `GENERIC_IDX = 2` resolves the identifier length associated with
/// the third generic position:
///
/// ```ignore
/// <Global as IdentHashLenAccess4<
///     HASH_A,
///     HASH_B,
///     HASH_C,
///     HASH_D,
///     2,
