/// Resolves the counter tuple associated with an instance identified by one
/// compile-time identifier hash.
///
/// `A` is the `u64` const value produced by an identifier-hashing expression,
/// typically of the form `{ hash_ident(b"a-ident") }`. The hash identifies the
/// instance impl implemented towards `SelfTy`.
///
/// The associated `Counter` type is the complete typenum counter tuple
/// associated with the resolved instance. For a one-dimensional instance, the
/// tuple contains the counter for dimension `0`.
///
/// For example, an implementation may associate:
///
/// ```ignore
/// type Counter = (U2,);
/// ```
///
/// The counter can then be projected from the resolved tuple through
/// [`CountersGet<U0>`]:
///
/// ```ignore
/// <Global as CounterAccess1<{ hash_ident(b"foo") }, InstanceType>>::Counter
/// ```
///
/// resolves to `(U2,)`, whose `U0` element is `U2`.
pub trait CounterAccess1<const A: u64, SelfTy: ?Sized> {
    type Counter: CountersGet<U0>;
}

/// Resolves the counter tuple associated with an instance identified by a
/// two-element sequence of compile-time identifier hashes.
///
/// `A` and `B` are `u64` const values produced by identifier-hashing
/// expressions, typically of the form `{ hash_ident(b"ident") }`. Together
/// they preserve the ordered identifier sequence used to identify the
/// instance impl implemented towards `SelfTy`.
///
/// The associated `Counter` type is the complete typenum counter tuple
/// associated with the resolved instance. The tuple contains one counter for
/// each identifier dimension, with dimension `0` stored at `U0` and dimension
/// `1` stored at `U1`.
///
/// For example, an implementation may associate:
///
/// ```ignore
/// type Counter = (U0, U3);
/// ```
///
/// The tuple can then be queried independently at each dimension:
///
/// ```ignore
/// <Global as CounterAccess2<
///     { hash_ident(b"foo") },
///     { hash_ident(b"bar") },
///     InstanceType,
/// >>::Counter
/// ```
///
/// provides `U0` through [`CountersGet<U0>`] and `U3` through
/// [`CountersGet<U1>`].
pub trait CounterAccess2<const A: u64, const B: u64, SelfTy: ?Sized> {
    type Counter: CountersGet<U0> + CountersGet<U1>;
}

/// Resolves the counter tuple associated with an instance identified by a
/// three-element sequence of compile-time identifier hashes.
///
/// `A`, `B`, and `C` are `u64` const values produced by identifier-hashing
/// expressions, typically of the form `{ hash_ident(b"ident") }`. Their order
/// is the order of the identifiers used to identify the instance impl
/// implemented towards `SelfTy`.
///
/// The associated `Counter` type is the complete typenum counter tuple for
/// the resolved instance. Each tuple position corresponds to the same
/// dimension position in the identifier sequence.
///
/// For example:
///
/// ```text
/// identifier hashes:
///     A, B, C
///
/// counter tuple:
///     (U0, U1, U2)
/// ```
///
/// Each dimension is available through its corresponding [`CountersGet`]
/// implementation, allowing later type-level operations to select the
/// counter associated with an individual dimension.
pub trait CounterAccess3<const A: u64, const B: u64, const C: u64, SelfTy: ?Sized> {
    type Counter: CountersGet<U0> + CountersGet<U1> + CountersGet<U2>;
}

/// Resolves the counter tuple associated with an instance identified by a
/// four-element sequence of compile-time identifier hashes.
///
/// `A`, `B`, `C`, and `D` are `u64` const values produced by identifier-hashing
/// expressions, typically of the form `{ hash_ident(b"ident") }`. Their order
/// is the order of the identifiers used to identify the instance impl
/// implemented towards `SelfTy`.
///
/// The associated `Counter` type is the complete typenum counter tuple for
/// the resolved instance. Each tuple position corresponds to the same
/// dimension position in the identifier sequence.
///
/// For example:
///
/// ```text
/// identifier hashes:
///     A, B, C, D
///
/// counter tuple:
///     (U0, U1, U2, U3)
/// ```
///
/// Each dimension is available through its corresponding [`CountersGet`]
/// implementation, allowing later type-level operations to select an
/// individual counter from the resolved tuple.
pub trait CounterAccess4<const A: u64, const B: u64, const C: u64, const D: u64, SelfTy: ?Sized> {
    type Counter: CountersGet<U0> + CountersGet<U1> + CountersGet<U2> + CountersGet<U3>;
}

