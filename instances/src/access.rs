/// Resolves the identifier length associated with a counter generic position
/// within an instance identified by one compile-time identifier hash.
///
/// `A` is the `u64` const value produced by an identifier-hashing expression,
/// typically of the form `{ hash_ident(b"a-ident") }`. The hash identifies the
/// instance impl implemented towards `SelfTy`.
///
/// `GENERIC_IDX` selects the counter generic position whose corresponding
/// identifier length is being accessed.
///
/// The associated `Length` type is the typenum representation of the
/// identifier length at that generic position.
///
/// For example, given an instance identified by `A` with:
///
/// ```text
/// identifier:       a
/// generic index:    0
/// identifier length: 3
/// ```
///
/// the corresponding access may resolve as:
///
/// ```ignore
/// <Global as IdentHashLenAccess1<
///     { hash_ident(b"a") },
///     0,
///     InstanceType,
/// >>::Length
/// ```
///
/// and `Length` resolves to the typenum value representing `3`.
///
/// In most cases the length will be simply GENERIC_IDX + 1 in typenum.
pub trait IdentHashLenAccess1<const A: u64, const GENERIC_IDX: usize, SelfTy: ?Sized> {
    type Length: UnsignedTypeNum;
}

/// Resolves the identifier length associated with a counter generic position
/// within an instance identified by a two-element sequence of compile-time
/// identifier hashes.
///
/// `A` and `B` are `u64` const values produced by identifier-hashing
/// expressions, typically of the form `{ hash_ident(b"ident") }`. Together
/// they preserve the ordered identifier sequence used to identify the instance
/// impl implemented towards `SelfTy`.
///
/// `GENERIC_IDX` selects the counter generic position whose corresponding
/// identifier length is being accessed.
///
/// The associated `Length` type is the typenum representation of the
/// identifier length at the selected generic position.
///
/// For example, an instance identified by:
///
/// ```text
/// A, B
/// ```
///
/// may have identifier lengths:
///
/// ```text
/// generic index     identifier length
///       0                    3
///       1                    5
/// ```
///
/// The corresponding access:
///
/// ```ignore
/// <Global as IdentHashLenAccess2<
///     { hash_ident(b"a") },
///     { hash_ident(b"bbbbb") },
///     1,
///     InstanceType,
/// >>::Length
/// ```
///
/// resolves to the typenum value representing `5`.
///
/// In most cases the length will be simply GENERIC_IDX + 1 in typenum.
pub trait IdentHashLenAccess2<const A: u64, const B: u64, const GENERIC_IDX: usize, SelfTy: ?Sized>
{
    type Length: UnsignedTypeNum;
}

/// Resolves the identifier length associated with a counter generic position
/// within an instance identified by a three-element sequence of compile-time
/// identifier hashes.
///
/// `A`, `B`, and `C` are `u64` const values produced by identifier-hashing
/// expressions, typically of the form `{ hash_ident(b"ident") }`. Their order
/// is the order of the identifiers used to identify the instance impl
/// implemented towards `SelfTy`.
///
/// `GENERIC_IDX` selects the counter generic position whose corresponding
/// identifier length is being accessed.
///
/// The associated `Length` type is the typenum representation of the
/// identifier length at the selected generic position.
///
/// For example:
///
/// ```text
/// identifier path:
///     A, B, C
///
/// generic index:
///     0    1    2
///
/// identifier length:
///     3    5    7
/// ```
///
/// Selecting `GENERIC_IDX = 1` therefore resolves the identifier length
/// associated with the second generic position:
///
/// ```ignore
/// <Global as IdentHashLenAccess3<
///     HASH_A,
///     HASH_B,
///     HASH_C,
///     1,
///     InstanceType,
/// >>::Length
/// ```
///
/// The resolved `Length` is the typenum representation of `5`.
///
/// In most cases the length will be simply GENERIC_IDX + 1 in typenum.
pub trait IdentHashLenAccess3<
    const A: u64,
    const B: u64,
    const C: u64,
    const GENERIC_IDX: usize,
    SelfTy,
>
{
    type Length: UnsignedTypeNum;
}

/// Resolves the identifier length associated with a counter generic position
/// within an instance identified by a four-element sequence of compile-time
/// identifier hashes.
///
/// `A`, `B`, `C`, and `D` are `u64` const values produced by identifier-hashing
/// expressions, typically of the form `{ hash_ident(b"ident") }`. Their order
/// is the order of the identifiers used to identify the instance impl
/// implemented towards `SelfTy`.
///
/// `GENERIC_IDX` selects the counter generic position whose corresponding
/// identifier length is being accessed.
///
/// The associated `Length` type is the typenum representation of the
