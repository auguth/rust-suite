// ``````````````````````````````` BOUNDARY ACCESS `````````````````````````````````
// ===============================================================================

/// Resolves the boundary counter tuple and the final identifier hash for the
/// root identifier sequence.
///
/// `BoundaryAccess0` is used when there is no preceding identifier sequence.
/// `SelfTy` alone therefore identifies the contextual instance whose
/// identifiers form the boundary.
///
/// `FINAL` is the hash of the final identifier occurring at this boundary.
///
/// For example, if the identifiers at the root boundary are:
///
/// ```text
/// a
/// b
/// c
///
/// FINAL = hash(c)
/// ```
///
/// The associated `Boundary` type is the complete typenum counter tuple for
/// the boundary and provides access to dimension `0` through
/// [`CountersGet<U0>`].
///
/// ```ignore
/// impl BoundaryAccess0<InstanceType> for Global {
///     const FINAL: u64 = { hash_ident(b"c") };
///     type Boundary = (U2,);
/// }
/// ```
///
/// The boundary information can then be recovered through:
///
/// ```ignore
/// <Global as BoundaryAccess0<InstanceType>>::FINAL
/// <Global as BoundaryAccess0<InstanceType>>::Boundary
/// ```
pub trait BoundaryAccess0<SelfTy: ?Sized> {
    const FINAL: u64;
    type Boundary: CountersGet<U0>;
}

/// Resolves the boundary counter tuple and the final identifier hash for a
/// boundary identified by one preceding compile-time identifier hash.
///
/// `A` is the `u64` const value produced by an identifier-hashing expression,
/// typically of the form `{ hash_ident(b"a-ident") }`. It identifies the
/// preceding identifier sequence whose immediate children form this boundary.
///
/// `FINAL` is the hash of the final identifier occurring immediately after
/// that preceding identifier sequence.
///
/// For example, given:
///
/// ```text
/// a, b
/// a, c
/// a, k
/// ```
///
/// the boundary identified by `a` has:
///
/// ```text
/// INITIAL = hash(b)
/// FINAL   = hash(k)
/// ```
///
/// `BoundaryAccess1` exposes the final hash and the complete counter tuple for
/// that boundary. The associated `Boundary` type provides access to dimensions
/// `0` and `1` through [`CountersGet`].
///
/// ```ignore
/// impl BoundaryAccess1<
///     { hash_ident(b"a") },
///     InstanceType,
/// > for Global {
///     const FINAL: u64 = { hash_ident(b"k") };
///     type Boundary = (U0, U3);
/// }
/// ```
pub trait BoundaryAccess1<const A: u64, SelfTy: ?Sized> {
    const FINAL: u64;
    type Boundary: CountersGet<U0> + CountersGet<U1>;
}

/// Resolves the boundary counter tuple and the final identifier hash for a
/// boundary identified by a two-element sequence of compile-time identifier
/// hashes.
///
/// `A` and `B` identify the preceding identifier sequence. The boundary
/// consists of the identifiers that immediately extend that sequence.
///
/// For example, given:
///
/// ```text
/// a, b, c
/// a, b, k
/// ```
///
/// the boundary identified by `a, b` has:
///
/// ```text
/// INITIAL = hash(c)
/// FINAL   = hash(k)
/// ```
///
/// `FINAL` therefore identifies the last identifier occurring at the boundary,
/// while the associated `Boundary` type contains the complete typenum counter
/// tuple for the `a, b` prefix.
///
/// Each tuple position corresponds to the same dimension position in the
/// preceding identifier sequence and can be accessed through the corresponding
/// [`CountersGet`] implementation.
pub trait BoundaryAccess2<const A: u64, const B: u64, SelfTy: ?Sized> {
    const FINAL: u64;
    type Boundary: CountersGet<U0> + CountersGet<U1> + CountersGet<U2>;
}

/// Resolves the boundary counter tuple and the final identifier hash for a
/// boundary identified by a three-element sequence of compile-time identifier
/// hashes.
///
/// `A`, `B`, and `C` identify the preceding identifier sequence. The boundary
/// consists of the identifiers that immediately extend that sequence.
///
/// For example, given:
///
/// ```text
/// a, b, c, d
/// a, b, c, k
/// ```
///
/// the boundary identified by `a, b, c` has:
///
/// ```text
/// INITIAL = hash(d)
/// FINAL   = hash(k)
/// ```
///
/// `FINAL` therefore identifies the last identifier occurring at the boundary,
/// while the associated `Boundary` type contains the complete typenum counter
/// tuple for the `a, b, c` prefix.
///
/// Each tuple position corresponds to the same dimension position in the
/// preceding identifier sequence and can be accessed through the corresponding
/// [`CountersGet`] implementation.
pub trait BoundaryAccess3<const A: u64, const B: u64, const C: u64, SelfTy: ?Sized> {
    const FINAL: u64;
    type Boundary: CountersGet<U0> + CountersGet<U1> + CountersGet<U2> + CountersGet<U3>;
}

