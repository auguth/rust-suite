/// Dispatches reverse-affiliate resolution from the most significant
/// counter dimension `D`.
///
/// `D` is the highest-order dimension in a four-counter tuple
/// `(A, B, C, D)`. The `IsZero` parameter selects whether that dimension
/// has reached zero.
///
/// When `D` is non-zero, the default reverse-affiliate step decrements `D`
/// while preserving all lower dimensions.
///
/// When `D` is zero, the zero-state implementation delegates resolution to
/// [`ReverseDispatchC`], making `C` the next most significant dimension that
/// can be decremented.
///
/// The zero-state implementation therefore acts as the recursive boundary
/// between dimensions: a dimension is exhausted before reverse resolution
/// proceeds to the next lower dimension.
pub trait ReverseDispatchD<IsZero: BoolTypeNum> {
    type Output: Marker;
}

/// Dispatches reverse-affiliate resolution from the most significant
/// remaining counter dimension `C`.
///
/// `C` is the highest-order dimension considered after `D` has reached zero
/// in a four-counter tuple, or the highest-order dimension in a three-counter
/// tuple `(A, B, C)`. The `IsZero` parameter selects whether `C` has reached
/// zero.
///
/// When `C` is non-zero, the default reverse-affiliate step decrements `C`
/// while preserving all lower dimensions.
///
/// When `C` is zero, the zero-state implementation delegates resolution to
/// [`ReverseDispatchB`], making `B` the next most significant dimension that
/// can be decremented.
///
/// Thus, the zero-state implementation is not itself a terminal case unless
/// `B` is also exhausted. It transfers reverse resolution to the next
/// dimension in significance order.
pub trait ReverseDispatchC<IsZero: BoolTypeNum> {
    type Output: Marker;
}

/// Dispatches reverse-affiliate resolution from the most significant
/// remaining counter dimension `B`.
///
/// `B` is the highest-order dimension considered after all higher dimensions
/// have reached zero, or the highest-order dimension in a two-counter tuple
/// `(A, B)`. The `IsZero` parameter selects whether `B` has reached zero.
///
/// When `B` is non-zero, the default reverse-affiliate step decrements `B`
/// while preserving the lower dimension `A`.
///
/// When `B` is zero, the zero-state implementation delegates resolution to
/// [`ReverseDispatchA`], making `A` the final dimension available for reverse
/// decrement.
///
/// This establishes the recursive progression from higher-significance
/// dimensions toward the least significant dimension.
pub trait ReverseDispatchB<IsZero: BoolTypeNum> {
    type Output: Marker;
}

/// Dispatches reverse-affiliate resolution for the least significant
/// remaining counter dimension `A`.
///
/// `A` is the final dimension reached after every more significant dimension
/// has been exhausted. The `IsZero` parameter selects whether `A` has reached
/// zero.
///
/// When `A` is non-zero, the default reverse-affiliate step decrements `A`.
///
/// When `A` is zero, the zero-state implementation is the terminal default:
/// no further reverse-affiliate step is possible, so the counter tuple is
/// returned unchanged.
///
/// `ReverseDispatchA` therefore provides the termination point of the
/// dimension-by-dimension reverse traversal.
pub trait ReverseDispatchA<IsZero: BoolTypeNum> {
    type Output: Marker;
}

