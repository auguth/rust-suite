// ===========================================================================
// `````````````````````````` BACK AFFILIATE ````````````````````````````````
// ===========================================================================

/// Resolves the back-affiliate counter tuple.
///
/// The resolution is performed in two stages. First, `Current` is checked
/// against the global minimum. If it is the global minimum, no back-affiliate
/// exists and `Current` is retained.
///
/// Otherwise, `ReverseNext` is compared with `Current`. When they are equal,
/// `Reverse` is selected; otherwise `ReverseFloor` is selected.
///
/// Inputs:
///
/// ```text
/// Current
/// Reverse
/// ReverseNext
/// ReverseFloor
/// ```
///
/// Resolution:
///
/// ```text
/// Current == GlobalMin
///     => Current
///
/// Current != GlobalMin
///     => ReverseNext == Current
///
/// ReverseNext == Current
///     => Reverse
///
/// ReverseNext != Current
///     => ReverseFloor
/// ```
///
/// The associated `Output` type is therefore the counter tuple determined
/// by these two compile-time decisions.
pub trait BackAffiliate<Reverse, ReverseNext, ReverseFloor, IsGlobalMin>
where
    Reverse: Marker,
    ReverseNext: Marker,
    ReverseFloor: Marker,
    IsGlobalMin: BoolTypeNum,
{
    type Output: Marker;
}

/// Dispatches back-affiliate resolution according to whether `Current` is
/// the global minimum.
///
/// When `IsGlobalMin` is true, the global-minimum case is terminal and
/// `Current` is returned unchanged.
///
/// When `IsGlobalMin` is false, the resolution continues to
/// [`BackAffiliateEqualityDispatch`], which determines whether `Reverse` or
/// `ReverseFloor` is the appropriate result.
pub trait BackAffiliateGlobalMinDispatch<Reverse, ReverseNext, ReverseFloor, IsGlobalMin>
where
    Reverse: Marker,
    ReverseNext: Marker,
    ReverseFloor: Marker,
    IsGlobalMin: BoolTypeNum,
{
    type Output: Marker;
}

/// Dispatches back-affiliate resolution according to whether `ReverseNext`
/// is equal to `Current`.
///
/// This dispatch is reached only after `Current` has been determined not to
/// be the global minimum.
///
/// When `CountersEqual` is true, `ReverseNext` identifies the current
/// position's reverse successor, so `Reverse` is selected.
///
/// When `CountersEqual` is false, `ReverseNext` does not equal `Current`, so
/// the back-affiliate resolves to `ReverseFloor`.
pub trait BackAffiliateEqualityDispatch<Reverse, ReverseFloor, CountersEqual>
where
    Reverse: Marker,
    ReverseFloor: Marker,
    CountersEqual: BoolTypeNum,
{
    type Output: Marker;
}

/// Global-minimum case.
///
/// ```text
/// if Current == GlobalMin => Current
/// ```
///
/// The current counter tuple is already at the global minimum, so no further
/// back-affiliate resolution is performed.
impl<Current, Reverse, ReverseNext, ReverseFloor>
    BackAffiliateGlobalMinDispatch<Reverse, ReverseNext, ReverseFloor, B1> for Current
where
    Current: Marker,
    Reverse: Marker,
    ReverseNext: Marker,
    ReverseFloor: Marker,
{
    type Output = Current;
}

/// Non-global-minimum case.
///
/// ```text
/// if Current != GlobalMin => evaluate equality dispatch
/// ```
///
/// The current counter tuple is not at the global minimum, so resolution
/// continues by comparing `Current` with `ReverseNext`.
impl<Current, Reverse, ReverseNext, ReverseFloor>
    BackAffiliateGlobalMinDispatch<Reverse, ReverseNext, ReverseFloor, B0> for Current
where
    Current: CountersEqual<ReverseNext>,
    Current: BackAffiliateEqualityDispatch<
            Reverse,
            ReverseFloor,
            <Current as CountersEqual<ReverseNext>>::Output,
        >,
    Current: Marker,
    Reverse: Marker,
    ReverseNext: Marker,
    ReverseFloor: Marker,
    <Current as CountersEqual<ReverseNext>>::Output: BoolTypeNum,
{
    type Output = <Current as BackAffiliateEqualityDispatch<
        Reverse,
        ReverseFloor,
        <Current as CountersEqual<ReverseNext>>::Output,
    >>::Output;
}

/// Equality case.
///
/// ```text
/// if ReverseNext == Current => Reverse
/// ```
///
/// `ReverseNext` is equal to `Current`, so `Reverse` is the resolved
/// back-affiliate counter tuple.
impl<Current, Reverse, ReverseFloor> BackAffiliateEqualityDispatch<Reverse, ReverseFloor, B1>
    for Current
where
    Current: Marker,
    Reverse: Marker,
    ReverseFloor: Marker,
{
    type Output = Reverse;
}

/// Inequality case.
///
/// ```text
/// if ReverseNext != Current => ReverseFloor
/// ```
///
/// `ReverseNext` is not equal to `Current`, so the back-affiliate resolves to
/// `ReverseFloor`.
impl<Current, Reverse, ReverseFloor> BackAffiliateEqualityDispatch<Reverse, ReverseFloor, B0>
    for Current
where
    Current: Marker,
    Reverse: Marker,
    ReverseFloor: Marker,
{
    type Output = ReverseFloor;
}

/// Entry point for back-affiliate resolution.
///
/// The resolution first determines whether `Current` is the global minimum.
/// If it is, `Current` is returned unchanged.
///
/// Otherwise, `Current` is compared with `ReverseNext`. When they are equal,
/// `Reverse` is selected; when they differ, `ReverseFloor` is selected.
///
/// Example:
///
/// ```text
/// Current      = (U0, U0, U5)
/// Reverse      = (U0, U0, U4)
/// ReverseNext  = (U0, U0, U5)
/// ReverseFloor = (U0, U0, U0)
///
/// Current != GlobalMin
/// ReverseNext == Current
///
/// Output = Reverse
/// ```
///
/// Example:
///
/// ```text
/// Current      = (U0, U0, U7)
/// Reverse      = (U0, U0, U6)
/// ReverseNext  = (U0, U0, U9)
/// ReverseFloor = (U0, U0, U0)
///
/// Current != GlobalMin
/// ReverseNext != Current
///
/// Output = ReverseFloor
/// ```
///
/// Example:
///
/// ```text
/// Current = GlobalMin
///
/// Output = Current
/// ```
///
/// `BackAffiliate` provides the public entry point while
/// [`BackAffiliateGlobalMinDispatch`] and
/// [`BackAffiliateEqualityDispatch`] perform the individual compile-time
/// decisions.
impl<Current, Reverse, ReverseNext, ReverseFloor, IsGlobalMin>
    BackAffiliate<Reverse, ReverseNext, ReverseFloor, IsGlobalMin> for Current
where
    Current: BackAffiliateGlobalMinDispatch<Reverse, ReverseNext, ReverseFloor, IsGlobalMin>,
    Current: Marker,
    Reverse: Marker,
    ReverseNext: Marker,
    ReverseFloor: Marker,
    IsGlobalMin: BoolTypeNum,
{
    type Output = <Current as BackAffiliateGlobalMinDispatch<
        Reverse,
        ReverseNext,
        ReverseFloor,
        IsGlobalMin,
    >>::Output;
}

