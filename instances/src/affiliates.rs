//! Internal type-level counter affiliation operations.
//!
//! This module contains the type-level operations used by the instances
//! macros to navigate and resolve positions within generated counter spaces.
//!
//! The traits and marker types defined here are implementation details of the
//! instances macros and should only be used by code generated by those macros.
//! They are not intended for direct use by users or by unrelated crate code.
//!
//! Their public visibility exists only to allow generated implementations and
//! generated access code to use these interfaces across the required Rust
//! visibility boundaries. Public visibility does not make these interfaces part
//! of the stable API.
//!
//! The signatures of these interfaces may therefore be changed freely as the
//! instances system evolves. Code outside the generated instances machinery
//! should not depend on their names, generic parameter ordering, associated
//! types, or other signature details.
//!
//! The module provides the following internal operations:
//!
//! - [`Affiliation`] - Identifies a type-level counter affiliation operation.
//! - [`DirectAffiliate`] - Resolves an affiliation directly from a complete counter tuple.
//! - `ReverseDispatch` - Performs dimension-by-dimension reverse traversal of a counter tuple.
//! - `CeilDispatch` - Resolves the ceil boundary through dimension-by-dimension dispatch.
//! - [`BackAffiliate`] - Resolves the final back-affiliate counter tuple from the current,
//!   reverse, reverse-next, and reverse-floor positions.
//! - [`CountersEqual`] - Compares corresponding positions of two counter tuples at the type level.
//!

