/// Identifies a type-level counter affiliation operation.
///
/// An affiliation describes how a counter tuple is related to another
/// position in its counter space. Concrete affiliation marker types select the
/// operation performed by [`DirectAffiliate`].
pub trait Affiliation {}

/// Selects the preceding counter position.
///
/// `Reverse` moves a counter tuple to the immediately preceding valid
/// position, with higher dimensions preserved while lower dimensions are
/// traversed according to the reverse-dispatch rules.
pub struct Reverse;

/// Selects the immediately following counter position.
pub struct Next;

/// Selects the immediate preceding position within the current affiliation context.
pub struct Back;

/// Selects the floor boundary of an individual counter of the counter space.
pub struct Floor;

/// Selects the ceil boundary of the counter space.
pub struct Ceil;

impl Affiliation for Reverse {}
impl Affiliation for Next {}
impl Affiliation for Back {}
impl Affiliation for Floor {}
impl Affiliation for Ceil {}

