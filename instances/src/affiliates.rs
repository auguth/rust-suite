/// Dispatches ceil resolution from the most significant counter dimension
/// `D`.
///
/// `D` is the highest-order dimension in a four-counter tuple
/// `(A, B, C, D)`. The `IsZero` parameter determines whether `D` has reached
/// zero.
///
/// When `D` is non-zero, the default implementation resolves the ceil value
/// by setting `D` to zero while preserving all lower dimensions.
///
/// When `D` is zero, the zero-state implementation delegates to
/// [`CeilDispatchC`], making `C` the next most significant dimension that can
/// be resolved.
///
/// The zero-state implementation therefore represents a dimension boundary:
/// the current dimension has already reached its ceil boundary, so resolution
/// continues with the next lower dimension.
///
/// The same dispatch trait is used for tuples with fewer counters by treating
/// the highest available dimension as the current most significant dimension.
///
/// ```text
/// (A, B, C, D)
///          D   current most significant dimension
///          C
///          B
///          A
/// ```
pub trait CeilDispatchD<IsZero: BoolTypeNum> {
    type Output: Marker;
}

/// Dispatches ceil resolution from the most significant remaining counter
/// dimension `C`.
///
/// `C` is the highest-order dimension considered after `D` has reached zero
/// in a four-counter tuple, and is the highest-order dimension of a
/// three-counter tuple `(A, B, C)`.
///
/// When `C` is non-zero, the default implementation resolves the ceil value
/// by setting `C` to zero while preserving all lower dimensions.
///
/// When `C` is zero, the zero-state implementation delegates to
/// [`CeilDispatchB`], making `B` the next most significant dimension that can
/// be resolved.
///
/// Thus, the [`B0`] implementation performs the ceil operation at the current
/// dimension, while the [`B1`] implementation transfers resolution to the next
/// lower dimension.
///
/// ```text
/// (A, B, C)
///       C   current most significant dimension
///       B
///       A
/// ```
pub trait CeilDispatchC<IsZero: BoolTypeNum> {
    type Output: Marker;
}

/// Dispatches ceil resolution from the most significant remaining counter
/// dimension `B`.
///
/// `B` is the highest-order dimension considered after all higher dimensions
/// have reached zero, and is the highest-order dimension of a two-counter
/// tuple `(A, B)`.
///
/// When `B` is non-zero, the default implementation resolves the ceil value
/// by setting `B` to zero while preserving the lower dimension `A`.
///
/// When `B` is zero, the zero-state implementation delegates to
/// [`CeilDispatchA`], making `A` the final dimension available for ceil
/// resolution.
///
/// This establishes the recursive progression from higher-significance
/// dimensions toward the least significant dimension.
///
/// ```text
/// (A, B)
///    B   current most significant dimension
///    A
/// ```
pub trait CeilDispatchB<IsZero: BoolTypeNum> {
    type Output: Marker;
}

/// Dispatches ceil resolution for the least significant remaining counter
/// dimension `A`.
///
/// `A` is the final dimension reached after every more significant dimension
/// has reached zero.
///
/// When `A` is non-zero, the default implementation resolves the ceil value
/// by setting `A` to zero.
///
/// When `A` is already zero, the zero-state implementation is the terminal
/// default. No further dimension remains to resolve, so the tuple is returned
/// unchanged.
///
/// `CeilDispatchA` therefore provides the termination point of the
/// dimension-by-dimension ceil traversal.
///
/// ```text
/// (A)
///  A   final remaining dimension
/// ```
///
/// For the all-zero tuple, the existing zero state is already the ceil state,
/// so the terminal implementation preserves it unchanged.
pub trait CeilDispatchA<IsZero: BoolTypeNum> {
    type Output: Marker;
}

