/// Compares two counter tuples element by element.
///
/// The associated `Output` is [`B1`] when every corresponding counter is
/// equal, and [`B0`] when at least one counter differs.
///
/// Each counter position is compared independently with [`IsEqual`], and the
/// resulting boolean values are combined with [`BitAnd`].
pub trait CountersEqual<Rhs: Marker> {
    type Output: BoolTypeNum;
}

/// Equality result for the first counter dimension.
///
/// `EqA0` represents the equality result of the first corresponding counter.
type EqA0<A0, B0> = <A0 as IsEqual<B0>>::Output;

/// Compares two single-counter tuples element by element.
///
/// The corresponding counter pairs are compared:
///
/// ```text
/// (A0)
/// (B0)
/// ```
///
/// Their equality result is:
///
/// ```text
/// A0 == B0
/// ```
///
/// The resulting `Output` is [`B1`] when the two counter positions are equal,
/// and [`B0`] when they differ.
impl<A0, B0> CountersEqual<(B0,)> for (A0,)
where
    A0: IsEqual<B0>,
    EqA0<A0, B0>: BoolTypeNum,
    (B0,): Marker,
{
    type Output = EqA0<A0, B0>;
}

/// Equality result for the first two counter dimensions.
///
/// `EqA1` combines the equality results of the first two corresponding
/// counters into a single type-level boolean.
type EqA1<A0, A1, B0, B1> =
    <<A0 as IsEqual<B0>>::Output as BitAnd<<A1 as IsEqual<B1>>::Output>>::Output;

/// Compares two two-counter tuples element by element.
///
/// The corresponding counter pairs are compared:
///
/// ```text
/// (A0, A1)
/// (B0, B1)
/// ```
///
/// Their equality results are combined with `BitAnd`:
///
/// ```text
/// A0 == B0
/// A1 == B1
///
/// (A0 == B0) AND (A1 == B1)
/// ```
///
/// The resulting `Output` is [`B1`] only when both counter positions are
/// equal. If any corresponding counter differs, the result is [`B0`].
impl<A0, A1, B0, B1> CountersEqual<(B0, B1)> for (A0, A1)
where
    A0: IsEqual<B0>,
    A1: IsEqual<B1>,
    <A0 as IsEqual<B0>>::Output: BitAnd<<A1 as IsEqual<B1>>::Output>,
    EqA1<A0, A1, B0, B1>: BoolTypeNum,
    (B0, B1): Marker,
{
    type Output = EqA1<A0, A1, B0, B1>;
}

/// Equality result for the first three counter dimensions.
///
/// `EqA2` combines the equality results of the first three corresponding
/// counters into a single type-level boolean.
type EqA2<A0, A1, A2, B0, B1, B2> =
    <EqA1<A0, A1, B0, B1> as BitAnd<<A2 as IsEqual<B2>>::Output>>::Output;

/// Compares two three-counter tuples element by element.
///
/// The corresponding counter pairs are compared:
///
/// ```text
/// (A0, A1, A2)
/// (B0, B1, B2)
/// ```
///
/// Their equality results are combined with `BitAnd`:
///
/// ```text
/// A0 == B0
/// A1 == B1
/// A2 == B2
///
/// (A0 == B0) AND (A1 == B1) AND (A2 == B2)
/// ```
///
/// The resulting `Output` is [`B1`] only when all three counter positions
/// are equal. If any corresponding counter differs, the result is [`B0`].
impl<A0, A1, A2, B0, B1, B2> CountersEqual<(B0, B1, B2)> for (A0, A1, A2)
where
    A0: IsEqual<B0>,
    A1: IsEqual<B1>,
    A2: IsEqual<B2>,
    <A0 as IsEqual<B0>>::Output: BitAnd<<A1 as IsEqual<B1>>::Output>,
    EqA1<A0, A1, B0, B1>: BitAnd<<A2 as IsEqual<B2>>::Output>,
    EqA2<A0, A1, A2, B0, B1, B2>: BoolTypeNum,
    (B0, B1, B2): Marker,
{
    type Output = EqA2<A0, A1, A2, B0, B1, B2>;
}

/// Equality result for the first four counter dimensions.
///
/// `EqA3` combines the equality results of the first four corresponding
/// counters into a single type-level boolean.
type EqA3<A0, A1, A2, A3, B0, B1, B2, B3> =
    <EqA2<A0, A1, A2, B0, B1, B2> as BitAnd<<A3 as IsEqual<B3>>::Output>>::Output;

/// Compares two four-counter tuples element by element.
///
/// The corresponding counter pairs are compared:
///
/// ```text
/// (A0, A1, A2, A3)
/// (B0, B1, B2, B3)
/// ```
///
/// Their equality results are combined with `BitAnd`:
///
/// ```text
/// A0 == B0
/// A1 == B1
/// A2 == B2
/// A3 == B3
///
/// (A0 == B0) AND (A1 == B1) AND (A2 == B2) AND (A3 == B3)
/// ```
///
/// The resulting `Output` is [`B1`] only when all four counter positions
/// are equal. If any corresponding counter differs, the result is [`B0`].
impl<A0, A1, A2, A3, B0, B1, B2, B3> CountersEqual<(B0, B1, B2, B3)> for (A0, A1, A2, A3)
where
    A0: IsEqual<B0>,
    A1: IsEqual<B1>,
    A2: IsEqual<B2>,
    A3: IsEqual<B3>,
    <A0 as IsEqual<B0>>::Output: BitAnd<<A1 as IsEqual<B1>>::Output>,
    EqA1<A0, A1, B0, B1>: BitAnd<<A2 as IsEqual<B2>>::Output>,
    EqA2<A0, A1, A2, B0, B1, B2>: BitAnd<<A3 as IsEqual<B3>>::Output>,
    EqA3<A0, A1, A2, A3, B0, B1, B2, B3>: BoolTypeNum,
    (B0, B1, B2, B3): Marker,
{
    type Output = EqA3<A0, A1, A2, A3, B0, B1, B2, B3>;
}
