/// Resolves a direct affiliation of a counter tuple.
///
/// `Affiliate` specifies the affiliation operation to apply to the counter
/// tuple, while the associated `Output`] type represents the resulting
/// counter tuple.
///
/// Direct affiliation operates on the complete counter tuple as a single
/// type-level value. The concrete affiliation determines how that tuple is
/// transformed.
///
/// The [`Reverse`] affiliation resolves the preceding counter position,
/// while [`Ceil`] resolves the tuple at its ceil boundary.
///
/// `DirectAffiliate` therefore provides the common interface through which
/// higher-level type-level operations can request an affiliation without
/// directly depending on the dimensional dispatch implementation.
pub trait DirectAffiliate<Affiliate>
where
    Affiliate: Affiliation,
{
    type Output: Marker;
}

